(ns fastmath.signal.fir-test
  (:require [fastmath.signal.fir :as sut]
            [fastmath.vector :as v]
            [clojure.test :as t]))

(t/deftest firwin-cutoff
  (t/testing "wrong input"
    (t/are [in] (try (sut/firwin-cutoff nil in 100) false (catch Exception e (:cutoff (ex-data e))))
      0 100 50 [0.0] [100.0] [50.0 100.0] [1 2 50] [2 3 4 0]))
  (t/testing "lowpass"
    (t/are [in out] (v/edelta-eq out (sut/firwin-cutoff :lowpass in 100))
      49 [0.0 0.98]
      1 [0.0 0.02]
      25 [0.0 0.5]
      [25 35 45] [0.0 0.9]))
  (t/testing "highpass"
    (t/are [in out] (v/edelta-eq out (sut/firwin-cutoff :highpass in 100))
      49 [0.98 1.0]
      1 [0.02 1.0]
      25 [0.5 1.0]
      [25 35 45] [0.5 1.0]))
  (t/testing "bandstop"
    (t/are [in out] (v/edelta-eq out (sut/firwin-cutoff :bandstop in 100))
      49 [0.0 0.98]
      1 [0.0 0.02]
      25 [0.0 0.5]
      [25] [0.0 0.5]
      [25 30] [0.0 0.5 0.6 1.0]
      [25 30 45] [0.0 0.5 0.6 0.9]))
  (t/testing "bandpass"
    (t/are [in out] (v/edelta-eq out (sut/firwin-cutoff :bandpass in 100))
      49 [0.98 1.0]
      1 [0.02 1.0]
      25 [0.5 1.0]
      [25] [0.5 1.0]
      [25 30] [0.5 0.6]
      [25 30 45] [0.5 0.6 0.9 1.0])))

