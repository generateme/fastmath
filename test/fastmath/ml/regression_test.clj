(defn- binomial-sample
  "Random binomial response (0/1) from the logistic model of the first term, `n` rows with `p` terms."
  [n p rng]
  (let [zs (partition p (seeded-normals (* n p) rng))
        us (seeded-uniforms n rng)
        xs (mapv vec zs)
        ys (mapv (fn [x u] (if (< u (/ 1.0 (+ 1.0 (m/exp (- (first x)))))) 1.0 0.0)) xs us)]
    [xs ys]))

