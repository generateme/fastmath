(def ^:private fit-options-tight {:epsilon 1.0e-16 :max-iters 100})

(defn- fit-glm [ys xss opts] (sut/glm ys xss (merge fit-options-tight opts)))

;; random data from an explicit, seeded generator
(defn- seeded-normals [n rng] (r/->seq (r/distribution :normal {:rng rng}) n))
(defn- seeded-uniforms [n rng] (r/->seq (r/distribution :uniform-real {:rng rng}) n))

(defn- nan? [x] (and (number? x) (Double/isNaN (double x))))

(defn- error-data
  "Runs `f`, returns `[message ex-data]` of the thrown `ex-info`, `nil` when nothing is thrown."
  [f]
  (try (f) nil (catch clojure.lang.ExceptionInfo e [(ex-message e) (ex-data e)])))

(defn- rows-with-positive-weight
  "Rows of `xs` with a positive weight."
  [xs ws]
  (keep (fn [[x w]] (when (pos? w) x)) (map vector xs ws)))

(defn- check-glm-reference
  "Compares fitted `glm` with the reference map of the generator (`glm_info`)."
  [glm ref tol]
  (t/is (m/delta-eq (:intercept glm) (:intercept ref) tol))
  (t/is (v/delta-eq (:beta glm) (:beta ref) tol))
  (t/is (v/delta-eq (map :stderr (:coefficients glm)) (:stderr ref) tol))
  (t/is (m/delta-eq (get-in glm [:deviance :residual]) (:deviance ref) tol))
  (t/is (m/delta-eq (get-in glm [:deviance :null]) (:null-deviance ref) tol))
  (t/is (= (get-in glm [:df :residual]) (long (:df-residual ref))))
  (t/is (= (get-in glm [:df :null]) (long (:df-null ref))))
  (t/is (m/delta-eq (:dispersion glm) (:dispersion ref) tol))
  (t/is (m/delta-eq (get-in glm [:ll :aic]) (:aic ref) tol))
  (t/is (m/delta-eq (get-in glm [:ll :log-likelihood]) (:log-likelihood ref) tol))
  (t/is (m/delta-eq (get-in glm [:ll :bic]) (:bic ref) tol)))

