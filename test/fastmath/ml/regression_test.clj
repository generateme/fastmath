        (t/is (m/delta-eq (:sigma base) (:sigma model) 1.0e-8) (str e))
        (t/is (m/delta-eq (:t-value (second (:coefficients base))) (:t-value (second (:coefficients model))) 0.0 1.0e-7) (str e))
        (t/is (v/delta-eq (:hat (:leverage (sut/analysis base))) (:hat (:leverage (sut/analysis model))) 1.0e-8) (str e))))
    (t/testing "glm: weights and terms"
      ;; the stopping rule |dev - dev0| / (0.1 + |dev|) of IRLS (as in R) is not scale free: weights below 1e-6 stop early
