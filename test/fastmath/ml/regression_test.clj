(defn- lm-tests
  "§3.2. `ref-block` is an already-resolved {:model :analysis} map (the
  deftest call site owns loading and, for multi-call files, sub-key
  selection -- decouples this fn from I/O). `options` may carry a test-only
  `:newdata-xss` key (a seq of new-data points, see `check-predict`) -- it is
  passed straight through to `sut/lm` alongside the real fitting options,
  which simply ignores unknown keys, matching `glm-tests`' own
  `:no-analysis?`/`:qres?` convention."
  ([ys xss ref-block] (lm-tests ys xss nil ref-block))
  ([ys xss options ref-block]
   (let [lm (sut/lm ys xss options)
         analysis (sut/analysis lm)]
     (t/is (m/delta-eq (:intercept lm) (get-in ref-block [:model :intercept])))
     (t/is (v/delta-eq (:beta lm) (get-in ref-block [:model :beta])))
     (check-coefficients (:coefficients lm) (get-in ref-block [:model :coefficients]))
     (check-xtxinv (:xtxinv lm) (get-in ref-block [:model :xtxinv]))
     (check-df (:df lm) (get-in ref-block [:model :df]))
     (check-ll (:ll lm) (get-in ref-block [:model :ll]))
     (check-fit-lm lm (:model ref-block))
     (check-residuals-lm (:residuals lm) (get-in ref-block [:model :residuals]))
     (check-correlation (:correlation analysis) (get-in ref-block [:analysis :correlation]))
     (check-normality (:normality analysis) (get-in ref-block [:analysis :normality]))
     (check-analysis-residuals-lm (:residuals analysis) (get-in ref-block [:analysis :residuals]))
     (check-leverage (:leverage analysis) (get-in ref-block [:analysis :leverage]))
     (check-influence (:influence analysis) (get-in ref-block [:analysis :influence]))
     (when-let [predict-ref (get-in ref-block [:extra :predict])]
       (check-predict lm (:newdata-xss options) predict-ref)))))

