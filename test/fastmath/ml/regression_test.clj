;; §3.1: named comparators, fine-grained -- each performs one `t/is` per field.
;; Shared between LM and GLM (identical shape on both sides):

(defn- check-coefficients
  "3.1.1. `coefs` = (:coefficients lm-or-glm), a seq of per-coefficient maps.
  `ref` = {:estimate [...] :stderr [...] :t-value|:z-value [...] :p-value [...]}.
  Reads whichever of :t-value/:z-value `ref` carries."
  [coefs ref]
  (t/is (v/delta-eq (map :estimate coefs) (:estimate ref)))
  (t/is (v/delta-eq (map :stderr coefs) (:stderr ref)))
  (let [stat-key (if (contains? ref :t-value) :t-value :z-value)]
    (t/is (v/delta-eq (map stat-key coefs) (stat-key ref))))
  (t/is (v/delta-eq (map :p-value coefs) (:p-value ref))))

(defn- check-xtxinv
  "3.1.2."
  [xtxinv ref]
  (t/is (v/delta-eq (mat/mat->seq xtxinv) ref)))

(defn- check-correlation
  "3.1.3. `correlation` = (:correlation analysis), a matrix; `ref` is flat."
  [correlation ref]
  (t/is (v/delta-eq (flatten correlation) ref)))

(defn- check-leverage
  "3.1.4."
  [leverage ref]
  (t/is (v/delta-eq (:hat leverage) (:hat ref)))
  (t/is (v/delta-eq (:sigmas leverage) (:sigmas ref)))
  (t/is (v/delta-eq (flatten (:coefficients leverage)) (:coefficients ref))))

(defn- check-influence
  "3.1.5. Optional `cooks-tol` (GLM uses 1e-5, LM uses the default)."
  ([influence ref] (check-influence influence ref nil))
  ([influence ref cooks-tol]
   (t/is (if cooks-tol
           (v/delta-eq (:cooks-distance influence) (:cooks-distance ref) cooks-tol)
           (v/delta-eq (:cooks-distance influence) (:cooks-distance ref))))
   (t/is (v/delta-eq (:dffits influence) (:dffits ref)))
   (t/is (v/delta-eq (:covratio influence) (:covratio ref)))
   (t/is (v/delta-eq (flatten (:dfbetas influence)) (:dfbetas ref)))))

(defn- check-df
  "3.1.6. Key-presence tolerant: checks whichever keys `ref` carries
  (LM: :residual/:model, GLM: :residual/:null)."
  [df ref]
  (doseq [k (keys ref)]
    (t/is (== (get df k) (get ref k)))))

(defn- check-ll
  "3.1.7. Key-presence tolerant (LM carries extra :aic-rss/:bic-rss)."
  [ll ref]
  (doseq [k (keys ref)]
    (t/is (m/delta-eq (get ll k) (get ref k)))))

;; LM-specific:

(defn- check-residuals-lm
  "3.1.8."
  [residuals ref]
  (t/is (v/delta-eq (:raw residuals) (:raw ref)))
  (t/is (v/delta-eq (:weighted residuals) (:weighted ref))))

(defn- check-fit-lm
  "3.1.9."
  [lm ref]
  (t/is (v/delta-eq (:fitted lm) (:fitted ref)))
  (t/is (m/delta-eq (:sigma lm) (:sigma ref)))
  (t/is (m/delta-eq (:sigma2 lm) (:sigma2 ref)))
  (t/is (m/delta-eq (:r-squared lm) (:r-squared ref)))
  (t/is (m/delta-eq (:adjusted-r-squared lm) (:adjusted-r-squared ref)))
  (t/is (m/delta-eq (:f-statistic lm) (:f-statistic ref))))

(defn- check-normality
  "3.1.10."
  [normality ref]
  (t/is (m/delta-eq (:skewness normality) (:skewness ref)))
  (t/is (m/delta-eq (:kurtosis normality) (:kurtosis ref)))
  (t/is (m/delta-eq (get-in normality [:durbin-watson :raw]) (:durbin-watson ref))))

(defn- check-analysis-residuals-lm
  "3.1.11."
  [residuals ref]
  (t/is (v/delta-eq (:standardized residuals) (:standardized ref)))
  (t/is (v/delta-eq (:studentized residuals) (:studentized ref))))

;; New-data prediction (fit/stderr/confidence-interval), shared by LM and GLM.
;; `model` is a fitted `LMData`/`GLMData` (implements `IFn`); `newdata-xss` is
;; a seq of points ready to pass straight to `model`/`sut/predict` as-is (i.e.
;; already offset-prepended, matching `with-offset`'s convention, when the
;; model was fit with an offset -- `predict`'s own `:transformer` application
;; happens internally, after offset extraction). `ref` = {:fit [...] :stderr
;; [...] :confidence-interval [[lo hi] ...]}, generated by
;; `fastmath.dev.regression-ref-gen`'s `predict-lm-oracle`/`predict-glm-oracle`.
(defn- check-predict
  [model newdata-xss ref]
  (let [preds (map #(model % true) newdata-xss)]
    (t/is (v/delta-eq (map :fit preds) (:fit ref)))
    (t/is (v/delta-eq (map :stderr preds) (:stderr ref)))
    (t/is (v/delta-eq (mapcat :confidence-interval preds) (flatten (:confidence-interval ref))))))

