;; GLM-specific comparators (§3.1.12-3.1.16, 3.1.19). `check-coefficients`,
;; `check-xtxinv`, `check-correlation`, `check-leverage`, `check-influence`,
;; `check-df`, `check-ll` above are already shared with LM.

(defn- check-residuals-glm
  "3.1.12."
  [residuals ref]
  (t/is (v/delta-eq (:working residuals) (:working ref) 1.0e-5))
  (t/is (v/delta-eq (:deviance residuals) (:deviance ref)))
  (t/is (v/delta-eq (:pearson residuals) (:pearson ref)))
  (t/is (v/delta-eq (:raw residuals) (:raw ref) 1.0e-4)))

(defn- check-fit-glm
  "3.1.13. :deviance :null is not checked here, `glm-tests` compares it unless
  :compare-deviance-null? is explicitly false."
  [glm ref]
  (t/is (v/delta-eq (:fitted glm) (:fitted ref) 1.0e-4))
  (t/is (m/delta-eq (:dispersion glm) (:dispersion ref)))
  (t/is (m/delta-eq (get-in glm [:deviance :residual]) (get-in ref [:deviance :residual]))))

(defn- check-weights
  "3.1.14."
  [weights ref]
  (t/is (v/delta-eq (:weights weights) (:weights ref)))
  (t/is (v/delta-eq (:initial weights) (:initial ref))))

(defn- check-analysis-residuals-glm
  "3.1.15."
  [residuals ref]
  (t/is (v/delta-eq (:studentized residuals) (:studentized ref)))
  (t/is (v/delta-eq (get-in residuals [:standardized :deviance]) (get-in ref [:standardized :deviance])))
  (t/is (v/delta-eq (get-in residuals [:standardized :pearson]) (get-in ref [:standardized :pearson]))))

(defn- check-dose
  "3.1.16."
  [dose ref]
  (t/is (m/delta-eq (:dose dose) (:dose ref)))
  (t/is (m/delta-eq (:stderr dose) (:stderr ref))))

(defn- check-quantile-residuals
  "3.1.19."
  [qres ref]
  (t/is (v/delta-eq qres ref)))

(defn- glm-tests
  "§3.3. `ref-block` is an already-resolved {:model :analysis :extra} map.
  Dose is checked whenever fastmath's own fitted model has >1 coefficient AND
  the reference carries a (non-error) dose block -- mirrors the generator's
  own `(when (> (count (:coefficients model)) 1) ...)` gate exactly (fixing
  the original R-based `glm-tests`' `:coefficeints` typo, which had made its
  own dose comparison permanently vacuous)."
  ([ys xss ref-block] (glm-tests ys xss nil ref-block))
  ([ys xss options ref-block]
   (let [glm (sut/glm ys xss (merge {:epsilon 1.0e-16 :max-iters 100} options))
         analysis (sut/analysis glm)]
     (t/is (m/delta-eq (:intercept glm) (get-in ref-block [:model :intercept])))
     (t/is (v/delta-eq (:beta glm) (get-in ref-block [:model :beta])))
     (check-coefficients (:coefficients glm) (get-in ref-block [:model :coefficients]))
     (check-xtxinv (:xtxinv glm) (get-in ref-block [:model :xtxinv]))
     (check-df (:df glm) (get-in ref-block [:model :df]))
     (when-not (:no-ll? options)
       (check-ll (:ll glm) (get-in ref-block [:model :ll])))
     (check-fit-glm glm (:model ref-block))
     (when-not (false? (:compare-deviance-null? options))
       (t/is (m/delta-eq (get-in glm [:deviance :null]) (get-in ref-block [:model :deviance :null]))))
     (check-residuals-glm (:residuals glm) (get-in ref-block [:model :residuals]))
     (check-weights (:weights glm) (get-in ref-block [:model :weights]))
     (when-not (:no-analysis? options)
       (check-correlation (:correlation analysis) (get-in ref-block [:analysis :correlation]))
       (check-analysis-residuals-glm (:residuals analysis) (get-in ref-block [:analysis :residuals]))
       (check-leverage (:leverage analysis) (get-in ref-block [:analysis :leverage]))
       (check-influence (:influence analysis) (get-in ref-block [:analysis :influence]) 1.0e-5))
     (when (> (count (:coefficients glm)) 1)
       (let [dose-ref (get-in ref-block [:extra :dose])]
         (when (and dose-ref (not (:error dose-ref)))
           (check-dose (sut/dose glm) dose-ref))))
     (when-let [qres-ref (get-in ref-block [:extra :quantile-residuals])]
       (check-quantile-residuals (sut/quantile-residuals glm) qres-ref))
     (when-let [predict-ref (get-in ref-block [:extra :predict])]
       (check-predict glm (:newdata-xss options) predict-ref)))))

