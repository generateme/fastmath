;; §2.2: shared, memoized EDN reference loader -- all R-fitted reference
;; values live in `test/resources/regression/*_reference.edn` (generated by
;; `fastmath.dev.regression-ref-gen`), so no live R session is needed to run
;; this test suite.

(def ^:private load-ref
  "Load and parse one `test/resources/regression/<name>_reference.edn` file.
  Memoized: each file is read and parsed at most once per test run,
  regardless of how many deftests/calls reference it."
  (memoize
   (fn [name]
     (-> (str "regression/" name "_reference.edn")
         io/resource
         slurp
         edn/read-string))))

;; §2.3: `col` is a raw categorical column (a seq of keywords); `values` are
;; the non-reference levels to build 0/1 columns for, matching the original
;; tablecloth `one-hot`'s calling convention. The reference level is
;; whichever level of `col` is not in `values`. Delegates to `contrast/dummy`;
;; duplicated (not shared) with the generator's own copy, per §4.

(defn- one-hot
  [col values]
  (let [levels (distinct col)
        reference (first (remove (set values) levels))
        coding (contrast/dummy (cons reference values))
        columns (apply map vector (map (:mapping coding) col))]
    (zipmap values columns)))

;; §2.3 extension: `col1`/`col2` are raw categorical columns. Reproduces the
;; original tablecloth `mult-columns`' exact column order and default
;; (first-appearance, sort1?/sort2?=false) reference-level convention.

(defn- mult-columns
  [col1 col2]
  (let [cs1 (vec (rest (distinct col1)))
        cs2 (vec (rest (distinct col2)))
        oh1 (one-hot col1 cs1)
        oh2 (one-hot col2 cs2)
        onehot1-cols (map oh1 cs1)
        onehot2-cols (map oh2 cs2)
        interactions (for [c2 cs2 c1 cs1] (mapv * (oh1 c1) (oh2 c2)))]
    {:cs1 cs1 :cs2 cs2 :xss (apply map vector (concat onehot1-cols onehot2-cols interactions))}))

