      (doseq [e [-9 -4 4 7 12]
              :let [k (Math/pow 10.0 e)
                    model (fit-glm yc (map #(* k %) x) {:family :poisson})]]
        (t/is (m/delta-eq (:intercept base-glm) (:intercept model) 1.0e-8) (str "terms " e))
        (t/is (m/delta-eq (first (:beta base-glm)) (* k (first (:beta model))) 0.0 1.0e-8) (str "terms " e))
