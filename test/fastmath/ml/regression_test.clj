(t/deftest binomial-large-trials
  (let [x small-x
        s [1 2 3 5 6 8 9 9]
        proportion (mapv #(/ % 10.0) s)
        base (fit-glm proportion x {:family :binomial :weights (repeat 8 10)})]
    (t/testing "trials above the int range: the same fit as with the proportions, a finite AIC"
      (doseq [k [1.0e8 1.0e9 1.0e12]
              :let [pairs (map (fn [a] [(* k a) (* k (- 10 a))]) s)
                    model (fit-glm pairs x {:family :binomial})]]
        (t/is (v/delta-eq (:beta base) (:beta model) 1.0e-8) (str k))
        (t/is (m/delta-eq (:intercept base) (:intercept model) 1.0e-8) (str k))
        (t/is (Double/isFinite (get-in model [:ll :aic])) (str k))
        (t/is (Double/isFinite (get-in model [:ll :bic])) (str k))))
    (t/testing "the AIC is continuous at the switch of the algorithm, 2e9 trials"
      (let [fit (fn [k] (get-in (fit-glm (map (fn [a] [(* k a) (* k (- 10 a))]) s) x {:family :binomial}) [:ll :aic]))
            below (fit 1.99e8) above (fit 2.01e8)]
        ;; the AIC is of the order of the number of trials: relative difference of the neighbours
        (t/is (< (m/abs (/ (- above below) below)) 0.02))))))
