      (t/is (v/delta-eq (flatten basis) (flatten (map #(tr [%]) xs)) 1.0e-8) (str "degree " degree))
      (t/is (= (+ 4 degree) (count (tr [0.5]))))))
  (t/testing "invalid parameters"
    (doseq [[args option] [[[0.0 1.0 0 3] :nseg] [[0.0 1.0 -1 3] :nseg] [[0.0 1.0 4 0] :degree] [[0.0 1.0 4 -2] :degree]
                           [[1.0 1.0 4 3] :xl] [[1.0 0.0 4 3] :xl] [[##NaN 1.0 4 3] :xl] [[0.0 ##Inf 4 3] :xl]]]
      (t/is (= option (:option (second (error-data #(apply sut/b-spline-transformer args))))) (pr-str args)))
    (t/is (= :xl (:option (second (error-data #(sut/b-spline-transformer [2.0 2.0 2.0] 4 3))))) "constant data"))
  (t/testing "NaN gives NaN, outside of the knots gives zeros, the left edge and the right edge are 1 in sum"
    (let [tr (sut/b-spline-transformer 0.0 1.0 4 3)]
      (t/is (every? nan? (tr [##NaN])))
      (t/is (= 7 (count (tr [##NaN]))))
      (t/is (every? zero? (tr [100.0])))
      (t/is (m/delta-eq 1.0 (reduce + (tr [0.0])) 1.0e-12))
      (t/is (m/delta-eq 1.0 (reduce + (tr [1.0])) 1.0e-12))
      (t/is (m/delta-eq 1.0 (reduce + (tr [0.999999999])) 1.0e-12)))))

