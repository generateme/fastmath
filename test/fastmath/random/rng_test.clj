(deftest irandom-beyond-the-int-range-covers-the-range
  (doseq [a [:jdk :mersenne]]
    ;; Spec 1.3 asks for max > 2^32 - 2^12, but the expected gap between the maximum of 10^5 draws and the bound is
    ;; 2^32 / 10^5 = 43000 = 2^15.4: the condition holds with probability 9% only (observed gaps 5000..90000).
    ;; The limit 2^32 - 2^18 fails with probability exp(-6.1) = 0.2%; the old code never exceeded 4.
    (let [mx (+ 5 (bit-shift-left 1 32))
          lower-limit (- (bit-shift-left 1 32) (bit-shift-left 1 18))
          g (r/rng a 11)
          xs (draws-of-fn 100000 #(r/irandom g mx))
          ys (draws-of-fn 100000 #(r/irandom g 0 mx))]
      (is (< lower-limit (reduce max xs)) (str a " irandom mx, old: below 5"))
      (is (< lower-limit (reduce max ys)) (str a " irandom 0 mx")))))

;; ---------------------------------------------------------------- 1.5 grandom

(deftest grandom-mean-std
  (testing "grandom mean std = mean + std * g, bitwise (old: the same only in 70% of the draws)"
    (doseq [a [:jdk :mersenne :isaac :well512a]]
      (let [x (r/rng a 4) y (r/rng a 4)]
        (is (every? true? (draws-of-fn 10000 #(= (r/grandom x 3.7 1.3) (+ 3.7 (* 1.3 (r/grandom y))))))
            (str a)))))
  (testing "arity 1 and 2: unchanged, mean 0 is the old stream"
    (doseq [a algorithms
            :let [expected (get-in @baseline [:rng-streams a])]]
      (is (= (:grandom expected) (draws-of-fn 20 (let [g (r/rng a 42)] #(r/grandom g)))) (str a))
      (is (= (:grandom-std expected) (draws-of-fn 20 (let [g (r/rng a 42)] #(r/grandom g 2.5)))) (str a))
      (is (= (:grandom-mean-0 expected) (draws-of-fn 20 (let [g (r/rng a 42)] #(r/grandom g 0.0 2.5)))) (str a))))
  (testing "mean /= 0 differs from the old stream in the last bits only"
    (doseq [a algorithms
            :let [old (get-in @baseline [:rng-streams a :grandom-mean-nonzero])
                  actual (draws-of-fn 20 (let [g (r/rng a 42)] #(r/grandom g 3.7 1.3)))]]
      (is (every? true? (map #(m/delta-eq (double %1) (double %2) 1.0e-14) old actual)) (str a))))
  (testing "sample standard deviation with a large mean"
    (let [sd (fn [mean std n]
               (let [g (r/rng :mersenne 12)
                     xs (double-array (draws-of-fn n #(- (r/grandom g mean std) mean)))
                     mu (/ (areduce xs i s 0.0 (+ s (aget xs i))) n)]
                 (Math/sqrt (/ (areduce xs i s 0.0 (+ s (m/sq (- (aget xs i) mu)))) (dec n)))))]
      ;; the result 1e6 + 1e-10 g is a double on the grid of ulp(1e6) = 1.16e-10 (about the std): rounding adds
      ;; a variance of ulp^2/12, measured sd 1.053e-10 (+5.3%); the old formula gave 1.21e-10 (+21%) and 3% is not attainable
      (is (< 0.99e-10 (sd 1.0e6 1.0e-10 1000000) 1.06e-10))
      (is (< 0.97e-10 (sd 1.0e3 1.0e-10 1000000) 1.03e-10) "ulp(1e3) = 1.1e-13: within 3%"))))

