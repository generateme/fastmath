(ns fastmath.random.rng-test
  "Tests of the RNG layer of `fastmath.random` (Random Audit, work packages 1.1-1.9, 9.1, 9.2).

  Oracles (`test/resources/random/rng_reference.edn`, generated by `utils/fastmath/dev/generate_random_rng_reference.py`):
  numpy `MT19937` for `:mersenne`, a Python re-implementation of `java.util.Random` for `:jdk`, the WELL512a recurrence of the
  paper for `:well512a`, an independent port of the unbiased bounded long rule of the Spec for `lrandom`/`irandom`.
  The seeded outputs of the code before the audit are in `test/resources/random/baseline_reference.edn`.

  `:isaac` and the WELL variants other than `:well512a` have no external oracle: they are covered by statistical regression
  pins (fixed seeds), which detect a change of the stream, they do not prove its correctness."
  (:require [clojure.edn :as edn]
            [clojure.java.io :as io]
            [clojure.string :as str]
