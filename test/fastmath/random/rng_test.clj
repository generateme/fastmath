(defn- draws-of-fn [^long k f] (vec (repeatedly k f)))

(defn- sha256-hex
  [^String s]
  (let [bytes (.digest (MessageDigest/getInstance "SHA-256") (.getBytes s "US-ASCII"))]
    (apply str (map (fn [b] (format "%02x" (bit-and (long b) 0xff))) bytes))))

(defn- digest-of
  "SHA-256 of the decimal representations of `xs` joined by newlines (the digest of the reference generator)."
  [xs]
  (sha256-hex (str/join "\n" xs)))

(defn- first-mismatch
  "Index of the first position where the two sequences differ, `nil` when they are equal."
  [xs ys]
  (or (some (fn [[i a b]] (when (not= a b) i)) (map vector (range) xs ys))
      (when (not= (count xs) (count ys)) (min (count xs) (count ys)))))

(defn- ex-data-of
  "`ex-data` of the `ex-info` thrown by `f`, `::other` for another exception, `nil` when nothing is thrown."
  [f]
  (try (f) nil
       (catch clojure.lang.ExceptionInfo e (or (ex-data e) {}))
       (catch Throwable _ ::other)))

;; chi-square critical values (scipy.stats.chi2.ppf), the p-value of a test is above the level when the statistic is below
(def ^:private ^:const chi2-df2-p01 9.210340371976184)
(def ^:private ^:const chi2-df9-p001 27.877164)

(defn- chi-square
  "Pearson statistic of the counts against equal expected counts."
  ^double [^longs counts]
  (let [total (double (areduce counts i s 0 (+ s (aget counts i))))
        e (/ total (alength counts))]
    (areduce counts i s 0.0 (+ s (/ (m/sq (- (aget counts i) e)) e)))))

;; ---------------------------------------------------------------- streams vs reference (WP 1.*, 9.1)

(def ^:private stream-shapes
  "Shape of the reference file -> function drawing one value (the number of values is the length of the reference), exactness."
  {:ints [(fn [g] (r/irandom g)) :exact]
   :longs [(fn [g] (r/lrandom g)) :exact]
   :doubles [(fn [g] (r/drandom g)) :exact]
   :floats [(fn [g] (double (r/frandom g))) :exact]
   :booleans [(fn [g] (r/brandom g)) :exact]
   :gaussians [(fn [g] (r/grandom g)) :gauss]
   :irandom-10 [(fn [g] (r/irandom g 10)) :exact]
   :irandom-16 [(fn [g] (r/irandom g 16)) :exact]
   :irandom-1e9 [(fn [g] (r/irandom g 1000000000)) :exact]
   :irandom-range-m3-4 [(fn [g] (r/irandom g -3 4)) :exact]
   :lrandom-1000 [(fn [g] (r/lrandom g 1000)) :exact]
   :lrandom-range-m5-5 [(fn [g] (r/lrandom g -5 5)) :exact]
   :drandom-range-m2-6 [(fn [g] (r/drandom g -2.0 6.0)) :exact]
   ;; Spec 1.5: mean + std * g
   :grandom-10-2 [(fn [g] (r/grandom g 10.0 2.0)) :gauss]
   :brandom-p-0.3 [(fn [g] (r/brandom g 0.3)) :exact]})

(defn- stream-matches?
  [kind expected actual]
  (and (= (count expected) (count actual))
       (every? true? (map (fn [e a]
                            (if (= :gauss kind)
                              ;; Box-Muller / polar use log, sqrt, sin, cos: Python libm and Java differ in the last bits
                              ;; (observed max 2.2e-16), the tolerance is 1e-12
                              (m/delta-eq (double e) (double a) 1.0e-12)
                              (= e a)))
                          expected actual))))

(defn- check-stream-reference
  [algo-key]
  (doseq [[shape [f kind]] stream-shapes
          [seed expected] (get-in @reference [algo-key shape])]
    (let [g (r/rng algo-key seed)
          actual (draws-of-fn (count expected) #(f g))]
      (is (stream-matches? kind expected actual) (str algo-key " seed " seed " " shape)))))

(deftest mersenne-stream-vs-numpy
  (is (= 10 (count (get-in @reference [:mersenne :ints]))))
  (check-stream-reference :mersenne))

(deftest jdk-stream-vs-lcg
  (is (= 10 (count (get-in @reference [:jdk :ints]))))
  (check-stream-reference :jdk))

;; The independent oracle is the recurrence of the paper with the state fill documented in the generator
(deftest well512a-stream-vs-recurrence
  (is (= 10 (count (get-in @reference [:well512a :ints]))))
  (check-stream-reference :well512a))

;; ---------------------------------------------------------------- 1.1 unbiased bounded long

(deftest lrandom-unbiased-rule-vs-python-port
  (testing "mx = 3*2^61, 2^62+1, 10^18 and 2^32+5: 20000 draws of MT seed 42, SHA-256 of the stream and raw draws consumed"
    (doseq [[mx {:keys [draws sha256 head raw-consumed]}] (:lrandom-unbiased @reference)]
      (let [g (r/rng :mersenne 42)
            xs (vec (repeatedly (long draws) #(r/lrandom g mx)))]
        (is (= head (subvec xs 0 (count head))) (str "head, mx " mx))
        (is (= sha256 (digest-of xs)) (str "all values, mx " mx))
        (is (every? #(and (<= 0 (long %)) (< (long %) (long mx))) xs) (str "range, mx " mx))
        (let [twin (r/rng :mersenne 42)]
          (dotimes [_ (long raw-consumed)] (r/lrandom twin))
          (is (= (r/lrandom twin) (r/lrandom g)) (str "the number of rejected draws, mx " mx))))))
  (testing "rejections happen (the test would not distinguish the rule from the plain modulo otherwise)"
    (is (< 20000 (get-in @reference [:lrandom-unbiased 6917529027641081856 :raw-consumed])))))

(deftest irandom-wide-bound-uses-the-unbiased-long-rule
  (let [mx (+ 5 (bit-shift-left 1 32))
        {:keys [draws sha256 head]} (get-in @reference [:lrandom-unbiased mx])
        mk #(r/rng :mersenne 42)]
    (testing "irandom mx = lrandom mx beyond the int range"
      (let [g (mk) xs (draws-of-fn (long draws) #(r/irandom g mx))]
        (is (= head (subvec xs 0 (count head))))
        (is (= sha256 (digest-of xs)))))
    (testing "irandom 0 mx and lrandom 0 mx"
      (let [g (mk)] (is (= sha256 (digest-of (draws-of-fn (long draws) #(r/irandom g 0 mx))))))
      (let [g (mk)] (is (= sha256 (digest-of (draws-of-fn (long draws) #(r/lrandom g 0 mx)))))))
    (testing "an offset is added to the bounded value"
      (let [g (mk)
            xs (draws-of-fn (long draws) #(r/lrandom g 7 (+ 7 mx)))]
        (is (= sha256 (digest-of (map #(- (long %) 7) xs))))))))

