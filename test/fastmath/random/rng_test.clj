;; ---------------------------------------------------------------- statistical regression pins (no external oracle)

(def ^:private pin-algorithms [:isaac :well512a :well1024a :well19937a :well19937c :well44497a :well44497b])

(deftest statistical-regression-pins
  ;; REGRESSION PINS, NOT ORACLES: fixed seed 20260101, they fail when the stream of an algorithm changes into a
  ;; statistically bad one. Chi-square of irandom 10 (df 9, level 1e-3) and the bit balance of lrandom (z-test of every
  ;; one of the 64 bits, the family-wise level 1e-3 is |z| < 4.32).
  (doseq [a pin-algorithms]
    (testing (str a)
      (let [g (r/rng a 20260101)
            ^longs counts (long-array 10)]
        (dotimes [_ 1000000]
          (let [i (int (r/irandom g 10))]
            (aset counts i (inc (aget counts i)))))
        (is (< (chi-square counts) chi2-df9-p001) (str "chi-square irandom 10 " (chi-square counts))))
      (let [g (r/rng a 20260101)
            n 300000
            ^longs ones (long-array 64)]
        (dotimes [_ n]
          (let [x (r/lrandom g)]
            (dotimes [b 64]
              (when (bit-test x b) (aset ones b (inc (aget ones b)))))))
        (let [zs (map (fn [^long c] (/ (- c (/ n 2.0)) (/ (Math/sqrt n) 2.0))) ones)]
          (is (< (reduce max (map #(Math/abs (double %)) zs)) 4.32) "bit balance, max |z| over 64 bits"))))))
