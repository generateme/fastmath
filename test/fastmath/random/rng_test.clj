(deftest lrandom-chi-square-modulo-3
  ;; Spec 1.1b speaks of the residues mod 3, but 3 divides mx = 3 * 2^61, so the residues of the biased old formula are
  ;; uniform too (control below); the bias is in the three equal thirds of [0, mx), of width 2^61: shares 3/8, 3/8, 1/4
  ;; (measured, chi-square about 8e4 for 2*10^6 draws). Both classifications are tested.
  (let [mx (* 3 (bit-shift-left 1 61))
        classes (fn [f classify]
                  (let [^longs counts (long-array 3)]
                    (dotimes [_ 2000000]
                      (let [i (int (classify (long (f))))]
                        (aset counts i (inc (aget counts i)))))
                    counts))
        third (fn [^long x] (bit-shift-right x 61))
        residue (fn [^long x] (mod x 3))]
    (doseq [seed [1 2 3]]
      (let [g (r/rng :mersenne seed)
            ^RandomGenerator twin (r/rng :mersenne seed)
            new-thirds (chi-square (classes #(r/lrandom g mx) third))
            old-thirds (chi-square (classes #(mod (.nextLong twin) mx) third))]
        (is (< new-thirds chi2-df2-p01) (str "seed " seed " chi-square of the thirds " new-thirds))
        (is (< 1.0e4 old-thirds) (str "control, old formula, seed " seed " chi-square of the thirds " old-thirds)))
      (let [g (r/rng :mersenne seed)]
        (is (< (chi-square (classes #(r/lrandom g mx) residue)) chi2-df2-p01) (str "seed " seed " chi-square of the residues mod 3"))))))

