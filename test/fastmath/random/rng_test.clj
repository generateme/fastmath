(deftest rng-unknown-names
  (testing "the default method throws for every unregistered dispatch value"
    (doseq [[label f] {"(rng :jvm 1)" #(r/rng :jvm 1)
                       "(rng :unknown)" #(r/rng :unknown)
                       "(rng nil)" #(r/rng nil)
                       "(rng \"jdk\")" #(r/rng "jdk")
                       "(rng 1 2)" #(r/rng 1 2)
                       "(synced-rng :zzz)" #(r/synced-rng :zzz)
                       "(synced-rng nil 3)" #(r/synced-rng nil 3)}]
      (let [data (ex-data-of f)]
        (is (map? data) label)
        (is (= :invalid-input (:type data)) label)
        (is (= 'rng (:function data)) label)
        (is (= :rng-name (:property data)) label)
        (is (some #{:mersenne} (:expected data)) (str label " lists the registered names")))))
  (testing ":default is :jdk"
    (is (= (draws-of-fn 20 (let [g (r/rng :default 1)] #(r/irandom g)))
           (draws-of-fn 20 (let [g (r/rng :jdk 1)] #(r/irandom g)))))
    (is (instance? RandomGenerator (r/rng :default))))
  (testing "rngs-list: nine names, a snapshot without :default, all constructible"
    (is (= (set algorithms) (set r/rngs-list)))
    (is (= 9 (count r/rngs-list)))
    (doseq [a r/rngs-list]
      (is (instance? RandomGenerator (r/rng a)) (str a))
