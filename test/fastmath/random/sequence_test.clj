(deftest order-statistics-marginal-means
  ;; the i-th of n sorted uniforms is Beta(i, n - i + 1): mean i / (n + 1), variance i (n - i + 1) / ((n + 1)^2 (n + 2))
  (let [n 10
        reps 2000
        u01 (r/distribution :uniform-real {:lower 0.0 :upper 1.0})
        check (fn [label samples]
                (is (every? (fn [xs] (and (= n (count xs)) (apply < xs) (< 0.0 (first xs)) (< (last xs) 1.0))) samples)
                    (str label ": sorted, in (0,1)"))
                (dotimes [j n]
                  (let [i (inc j)
                        mu (/ i (+ n 1.0))
                        variance (/ (* i (- (+ n 1.0) i)) (* (m/sq (+ n 1.0)) (+ n 2.0)))
                        mean (/ (reduce + (map #(nth % j) samples)) reps)
                        z (/ (- mean mu) (m/sqrt (/ variance reps)))]
                    (is (< (m/abs z) 4.0) (str label " position " i " z = " z)))))]
    (let [rng (r/rng :mersenne 42)]
      (check "rng source" (vec (repeatedly reps #(vec (r/->seq rng n :uniform))))))
    (let [rng (r/rng :mersenne 43)]
      (check "distribution source" (vec (repeatedly reps #(vec (r/->seq u01 n :uniform rng))))))))

