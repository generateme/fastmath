(deftest ball-radius-cdf
  ;; KS distance of the radius from the cdf r^d, 20000 points, critical value 1.63 / sqrt(n) (level 1%), fixed seeds
  (doseq [d [1 2 3 4 5 10]]
    (let [n 20000
          rng (r/rng :mersenne (+ 1000 d))
          radii (map (fn [p] (m/sqrt (reduce + (map (fn [^double x] (* x x)) (flat p))))) (take n (r/sequence-generator :ball d rng)))
          dstat (ks-statistic radii (fn [^double x] (m/pow x d)))]
      (is (< dstat (/ 1.63 (m/sqrt n))) (str "d = " d " D = " dstat))))
  (testing "ball-random is the same stream as the :ball generator"
    (let [a (r/rng :mersenne 9) b (r/rng :mersenne 9)]
      (is (= (take 20 (map flat (r/sequence-generator :ball 3 a))) (repeatedly 20 #(flat (r/ball-random b 3))))))))

