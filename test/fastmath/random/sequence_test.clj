(ns fastmath.random.sequence-test
  "Tests of the sequence generators and of `->seq` of `fastmath.random` (Random Audit, work packages 2.1-2.8, 9.3).

  Oracles (`test/resources/random/sequence_reference.edn`, generated by `utils/fastmath/dev/generate_random_sequence_reference.py`):
  `scipy.stats.qmc.Sobol` for `:sobol`, an independent Kocis-Whiten Halton implementation for `:halton` (Commons Math variant,
  not the scipy one), mpmath (50 digits) for the R2 constants and the closed form `frac(0.5 + n * alpha)`, the jitter formula of
  Roberts' article for the jitter scales. Statistical checks use fixed seeds.
  The seeded outputs of the code before the audit are in `test/resources/random/baseline_reference.edn`."
  (:require [clojure.edn :as edn]
            [clojure.java.io :as io]
            [clojure.string :as str]
            [clojure.test :refer [deftest is testing]]
            [fastmath.core :as m]
            [fastmath.random :as r]
            [fastmath.vector :as v])
  (:import [fastmath.vector Vec2 Vec3 Vec4]))

(set! *warn-on-reflection* true)

(def ^:private reference
  (delay (edn/read-string (slurp (io/resource "random/sequence_reference.edn")))))

(def ^:private baseline
  (delay (edn/read-string (slurp (io/resource "random/baseline_reference.edn")))))

(def ^:private sampling-methods [:uniform :systematic :stratified :antithetic :r2 :sobol :halton])

(defn- flat
  "A point (number, Vec2, ..., vector) as a vector of doubles."
  [p]
  (if (number? p) [(double p)] (mapv double p)))

(defn- ex-data-of
  "`ex-data` of the `ex-info` thrown by `f`, `::other` for another exception, `nil` when nothing is thrown."
  [f]
  (try (f) nil
       (catch clojure.lang.ExceptionInfo e (or (ex-data e) {}))
       (catch Throwable _ ::other)))

(defn- invalid-input?
  ([f] (= :invalid-input (:type (ex-data-of f))))
  ([property f] (let [data (ex-data-of f)] (and (map? data) (= :invalid-input (:type data)) (= property (:property data))))))

(defn- max-abs-diff
  ^double [xs ys]
  (reduce (fn [^double mx [a b]] (m/max mx (m/abs (- (double a) (double b))))) 0.0
          (mapcat (fn [p q] (map vector (flat p) (flat q))) xs ys)))

(defn- circular-distance
  "Distance of two numbers on the circle [0,1)."
  ^double [^double a ^double b]
  (let [d (m/abs (- a b))] (m/min d (- 1.0 d))))

(defn- ks-statistic
  "Kolmogorov-Smirnov distance of the sorted sample `xs` from the cdf `f`."
  ^double [xs f]
  (let [n (count xs)]
    (double (reduce max 0.0 (map-indexed (fn [i x]
                                           (let [fx (double (f x))]
                                             (max (m/abs (- (/ (inc i) (double n)) fx))
                                                  (m/abs (- fx (/ i (double n)))))))
                                         (sort xs))))))

;; ---------------------------------------------------------------- reference: Sobol, Halton, R2

(deftest sobol-vs-scipy
  (doseq [[d {:keys [columns points]}] (:sobol @reference)]
    (let [actual (take 1000 (r/sequence-generator :sobol d))]
      (testing (str "d = " d)
        (is (= 1000 (count points)))
        ;; dyadic rationals: the points are exact
        (is (= points (mapv (fn [p] (subvec (flat p) 0 columns)) actual)))))))

(deftest halton-vs-kocis-whiten
  (doseq [[d {:keys [points]}] (:halton @reference)]
    (let [actual (take 200 (r/sequence-generator :halton d))]
      (testing (str "d = " d)
        (is (= 200 (count points)))
        (is (< (max-abs-diff points actual) 1.0e-15) "observed 0.0 (Commons Math = Kocis-Whiten)")))))

(deftest halton-is-not-the-plain-halton
  ;; the second point of the 2-d plain Halton (scipy) is [0.5 1/3], the weighted variant has [0.5 2/3]
  (is (m/delta-eq 0.5 (first (flat (second (r/sequence-generator :halton 2)))) 1.0e-15))
  (is (m/delta-eq (/ 2.0 3.0) (second (flat (second (r/sequence-generator :halton 2)))) 1.0e-15)))

(deftest first-points-of-sobol-and-halton-are-the-origin
  (doseq [g [:sobol :halton]
          d [1 2 5]]
    (is (every? zero? (flat (first (r/sequence-generator g d)))) (str g " " d))))

(deftest r2-constants-and-closed-form
  (testing "alpha_i = phi^-i, the constants are the first point minus the seed 0.5"
    (doseq [[d {:keys [alpha]}] (:r2-alpha @reference)
            :when (contains? (:r2 @reference) d)]
      (let [p (flat (first (r/sequence-generator :r2 d)))]
        (is (= d (count alpha)))
        ;; the first point is frac(0.5 + alpha), rounded once (<= 1.1e-16)
        (is (every? true? (map (fn [pi ai] (< (circular-distance (- pi 0.5) ai) 1.0e-15)) p alpha)) (str "d = " d)))))
  (testing "points n = 1..100 vs frac(0.5 + n * alpha) (mpmath)"
    (doseq [[d {:keys [points]}] (:r2 @reference)]
      (let [actual (take 100 (r/sequence-generator :r2 d))]
        (is (= 100 (count points)))
        ;; the library adds the double alpha n times: the error grows like n * (alpha double - alpha), up to 1e-16 per step;
        ;; observed max 1.09e-14 (d = 15, n = 100)
        (is (< (max-abs-diff points actual) 3.0e-14) (str "d = " d))))))

(deftest r2-all-dimensions-start-at-seed-plus-alpha
  (doseq [d (range 1 16)
          :let [p (flat (first (r/sequence-generator :r2 d)))
                alpha (get-in @reference [:r2-alpha d :alpha])]]
    (is (= d (count p)))
    (is (every? #(and (<= 0.0 (double %)) (< (double %) 1.0)) p))
    (is (every? true? (map (fn [pi ai] (< (circular-distance (- pi 0.5) ai) 1.0e-15)) p alpha)) (str d))))

(deftest return-shapes
  (doseq [g [:r2 :halton :sobol :default :gaussian :sphere :ball :uniform]
          [d cls] [[1 Double] [2 Vec2] [3 Vec3] [4 Vec4] [5 clojure.lang.PersistentVector] [6 clojure.lang.PersistentVector]]]
    (is (instance? cls (first (r/sequence-generator g d (r/rng :mersenne 1)))) (str g " " d))
    (is (instance? cls (first (r/jittered-sequence-generator g d 0.25 (r/rng :mersenne 1)))) (str "jittered " g " " d))
    (is (instance? cls (first (r/jittered-sequence-generator g d))) (str "jittered, no rng " g " " d))))

(deftest sequence-generators-list
  (let [l r/sequence-generators-list]
    (is (every? (set l) [:r2 :halton :sobol :default :gaussian :sphere :ball]))
    (is (some #{:default} l))
    (is (not-any? #{:uniform} l))))

