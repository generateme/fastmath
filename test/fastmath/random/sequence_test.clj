        (is (not= (vec (r/->seq d 10 method)) (vec (r/->seq d 10 method))) (str method))
        (is (not= (vec (r/->seq d 10 method nil)) (vec (r/->seq d 10 method nil))) (str method))))))

(deftest seq-rng-source-takes-no-fourth-argument
  (doseq [method sampling-methods]
    (let [data (ex-data-of #(r/->seq (r/rng :mersenne 1) 10 method (r/rng :mersenne 2)))]
      (is (map? data) (str method))
      (is (= :invalid-input (:type data)) (str method))
      (is (= :rng (:property data)) (str method))
      (is (some? (r/->seq (r/rng :mersenne 1) 10 method nil)))))
  (testing "a bad 4th argument for a distribution source"
    (is (= {:rng 5} (ex-data-of #(r/->seq (r/distribution :normal) 10 :uniform 5))))))

;; ---------------------------------------------------------------- 2.3 n and method

(deftest seq-n-table
  (let [source #(r/rng :mersenne 1)
        d (r/distribution :normal)]
    (testing "plain sampling (no method)"
      (is (= 3 (count (take 3 (r/->seq (source) nil)))) "nil n: infinite")
      (is (= 5 (count (r/->seq (source) 5))))
      (is (= () (r/->seq (source) 0)))
      (is (= () (r/->seq (source) -1)))
      (doseq [bad ["a" 2.5 :k]]
        (is (invalid-input? :n #(r/->seq (source) bad)) (pr-str bad)))
      (is (= 0 (count (r/->seq d 0))))
      (is (= () (r/->seq d -1)))
      (is (invalid-input? :n #(r/->seq d "a"))))
    (testing "with a method"
      (doseq [method sampling-methods
              src [(source) d]]
        (is (invalid-input? :n #(r/->seq src nil method)) (str method " requires n"))
        (doseq [bad ["a" 2.5]]
          (is (invalid-input? :n #(r/->seq src bad method)) (str method " " (pr-str bad))))
        (is (= () (r/->seq src -1 method)) (str method " -1"))
        (is (= () (r/->seq src 0 method)) (str method " 0"))
        (is (= 4 (count (r/->seq src 4 method))) (str method " 4"))))
    (testing "nil and false methods are plain sampling"
      (is (= 4 (count (r/->seq (source) 4 nil))))
      (is (= (vec (r/->seq (r/rng :mersenne 1) 4)) (vec (r/->seq (r/rng :mersenne 1) 4 nil))))
      (is (= (vec (r/->seq (r/rng :mersenne 1) 4)) (vec (r/->seq (r/rng :mersenne 1) 4 false)))))))

(deftest seq-invalid-method
  (doseq [method [:bogus "uniform" 1 :sobbol]
          src [(r/rng :mersenne 1) (r/distribution :normal)]]
    (let [data (ex-data-of #(r/->seq src 4 method))]
      (is (map? data) (pr-str method))
      (is (= :invalid-input (:type data)))
      (is (= :sampling-method (:property data)))
      (is (= (set sampling-methods) (set (:expected data))) "the 7 methods are listed")))
  (is (= 7 (count (:expected (ex-data-of #(r/->seq (r/rng :mersenne 1) 4 :bogus)))))))

(deftest seq-of-rng-is-uniform-doubles
