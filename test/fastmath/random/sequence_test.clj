(def ^:private dimension-table [0 -1 1 15 16 40 41 1000 1001 2.5 nil])

(defn- dimension-valid?
  [g d]
  (and (integer? d)
       (<= 1 (long d) (case g :r2 15 :halton 40 :sobol 1000 Long/MAX_VALUE))))

(deftest dimension-checks
  (doseq [assert? [true false]
          g [:r2 :halton :sobol :default :gaussian :sphere :ball :uniform]
          d dimension-table]
    (binding [*assert* assert?]
      (let [label (str g " dims " (pr-str d) " *assert* " assert?)
            rng (r/rng :mersenne 1)]
        (if (dimension-valid? g d)
          (do (is (some? (first (r/sequence-generator g d rng))) label)
              (is (some? (first (r/jittered-sequence-generator g d 0.25 rng))) (str "jittered " label)))
          (do (is (invalid-input? :dimensions #(r/sequence-generator g d rng)) label)
              (is (invalid-input? :dimensions #(r/jittered-sequence-generator g d 0.25 rng)) (str "jittered " label))))))))

(deftest dimension-check-messages-state-the-limit
  (doseq [[g limit] {:r2 15 :halton 40 :sobol 1000}]
    (let [data (ex-data-of #(r/sequence-generator g (inc limit)))]
      (is (= :invalid-input (:type data)))
      (is (= (inc limit) (:value data)))
      (is (re-find (re-pattern (str limit)) (str (:expected data))) (str g)))))

(deftest ball-random-validation
  (testing "dims"
    (doseq [d [0 -1 -2 -3 2.5 nil "a"]]
      (is (invalid-input? :dimensions #(r/ball-random (r/rng :mersenne 1) d)) (str "dims " (pr-str d)))
      (is (invalid-input? :dimensions #(r/ball-random d)) (str "dims " (pr-str d) ", default-rng form"))))
  (testing "rng: nil gives a fresh generator, anything else but a generator throws ex-info {:rng value}"
    (is (instance? Vec2 (r/ball-random nil 2)))
    (is (number? (r/ball-random nil 1)))
    (is (not= (r/ball-random nil 3) (r/ball-random nil 3)) "fresh unseeded generators")
    (let [d (r/distribution :normal)]
      (is (= {:rng d} (ex-data-of #(r/ball-random d 2)))))
    (is (= {:rng 5} (ex-data-of #(r/ball-random 5 2))))))

(deftest jitter-validation
  (doseq [jitter [##NaN ##Inf ##-Inf -0.1 -1 nil :a "1" (r/rng :mersenne 1)]]
    (is (invalid-input? :jitter #(r/jittered-sequence-generator :r2 2 jitter)) (str "jitter " (pr-str jitter)))
    (is (invalid-input? :jitter #(r/jittered-sequence-generator :default 2 jitter (r/rng :mersenne 1))) (str "jitter " (pr-str jitter))))
  (testing "valid: zero, integers, large numbers"
    (doseq [jitter [0 0.0 1 1.0 10.0 1.0e6]]
      (is (some? (first (r/jittered-sequence-generator :r2 2 jitter))) (str jitter))))
  (testing "a generator in the jitter position is an invalid jitter, a distribution as rng an ex-info {:rng d}"
    (let [d (r/distribution :normal)]
      (is (= {:rng d} (ex-data-of #(r/jittered-sequence-generator :r2 2 0.25 d))))
      (is (= {:rng d} (ex-data-of #(r/sequence-generator :default 2 d)))))))

(deftest jitter-zero-is-the-base-for-quasi-random-generators
