;; ---------------------------------------------------------------- jitter scale (Roberts)

(deftest jitter-scale-table
  ;; jittered point i = frac(base_i + scale(i) * u), u the i-th draws of the rng (one per coordinate) taken after the
  ;; draws of the previous points; scale(i) at jitter = 1.0 comes from the article (mpmath), dims 2 (Vec2) and 6 (array path)
  (doseq [[g {:keys [indices scale]}] (:jitter-scale @reference)
          d [2 6]]
    (testing (str g " dims " d)
      (let [seed 17
            points (vec (take 1001 (r/jittered-sequence-generator g d 1.0 (r/rng :mersenne seed))))
            base (vec (take 1001 (r/sequence-generator g d)))
            twin (r/rng :mersenne seed)
            draws (vec (repeatedly 1001 (fn [] (vec (repeatedly d #(r/drandom twin))))))]
        (doseq [[i s] (map vector indices scale)]
          (let [b (flat (base i))
                u (draws i)
                pt (flat (points i))]
            (is (every? true? (map (fn [bj uj pj] (< (circular-distance pj (m/frac (+ bj (* s uj)))) 1.0e-14)) b u pt))
                (str "i = " i))))))))

;; ---------------------------------------------------------------- 2.6 jittered :ball

(deftest jittered-ball-keeps-both-signs
  (doseq [d [1 2 3 4 5 6]
          jitter [0.25 1.0]]
    (let [pts (take 100000 (r/jittered-sequence-generator :ball d jitter (r/rng :mersenne (+ 100 d))))
          cs (mapcat flat pts)
          neg (count (filter neg? cs))
          total (count cs)]
      (is (every? #(and (<= -1.0 (double %)) (< (double %) 1.0)) cs) (str "d " d " jitter " jitter ": [-1, 1)"))
      (is (<= 0.45 (/ neg (double total)) 0.55) (str "d " d " jitter " jitter ": share of negative coordinates " (/ neg (double total)))))))

(deftest jittered-ball-wrap-keeps-the-sign
  ;; jitter 0: the point is wrap(ball point) = ((x + 1) mod 2) - 1 = x up to rounding (old: |x|). The jitter numbers are
  ;; still drawn, d after every ball point, so the twin generator skips them.
  (doseq [d [1 2 3 6]]
    (let [seed 5
          twin (r/rng :mersenne seed)
          expected (vec (for [_ (range 500)]
                          (let [p (r/ball-random twin d)]
                            (dotimes [_ d] (r/drandom twin))
                            (flat p))))
          actual (mapv flat (take 500 (r/jittered-sequence-generator :ball d 0.0 (r/rng :mersenne seed))))]
      (is (< (max-abs-diff expected actual) 5.0e-16) (str "d = " d ", rounding of (x + 1) mod 2 - 1 is at most 2.2e-16"))
      (is (some #(some neg? %) actual) (str "d = " d)))))

