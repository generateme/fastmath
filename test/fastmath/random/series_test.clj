(defn- sample-mean-sd
  [xs]
  (let [n (count xs)
        mean (/ (reduce + xs) n)
        sd (m/sqrt (/ (reduce + (map #(m/sq %) xs)) n))]
    [mean sd]))

(deftest white-noise-statistics
  ;; N = 2 * 10^5, |z| < 4: sd = sigma +- sigma / sqrt(2N), mean 0 +- sigma / sqrt(N), lag-1 acf 0 +- 1 / sqrt(N)
  (let [n 200000]
    (doseq [sigma [0.5 2.0 3.7]
            seed [1 2]
            :let [xs (vec (take n (r/white-noise (r/rng :mersenne seed) sigma)))
                  [mean sd] (sample-mean-sd xs)
                  lag1 (/ (reduce + (map * xs (rest xs))) (reduce + (map #(m/sq %) xs)))]]
      (is (< (m/abs (/ (- sd sigma) (/ sigma (m/sqrt (* 2.0 n))))) 4.0) (str "sd sigma " sigma " seed " seed))
      (is (< (m/abs (/ mean (/ sigma (m/sqrt n)))) 4.0) (str "mean sigma " sigma " seed " seed))
      (is (< (m/abs (* lag1 (m/sqrt n))) 4.0) (str "lag 1 sigma " sigma " seed " seed)))))

