(defn- autocovariance
  "Sample autocovariance (uncentered, the processes have mean 0) at lag `k`."
  ^double [^doubles xs ^long k]
  (let [n (alength xs)]
    (loop [i k
           s 0.0]
      (if (< i n)
        (recur (inc i) (+ s (* (aget xs i) (aget xs (- i k)))))
        (/ s (- n k))))))

(deftest arma-acf-and-variance-vs-theory
  ;; N = 2 * 10^5 outputs, 2 seeds, |z| < 4. The standard error of the sample acf is the Bartlett one (stored per sqrt(N)), that of
  ;; the variance sqrt(2 sum rho^2) per sqrt(N). The start of the processes is not stationary, the effect at N = 2e5 is negligible.
  (is (= 4 (count (:theory @reference))))
  (let [n 200000]
    (doseq [{:keys [id phi theta variance acf acf-se-sqrt-n variance-rel-se-sqrt-n]} (:theory @reference)
            seed [1 2]
            :let [xs (double-array (take n (series-with-default-signal phi theta {:rng (r/rng :mersenne seed)})))
                  g0 (autocovariance xs 0)
                  z-var (/ (- (/ g0 variance) 1.0) (/ variance-rel-se-sqrt-n (m/sqrt n)))]]
      (testing (str id " seed " seed)
        (is (< (m/abs z-var) 4.0) (str "variance z " z-var))
        (doseq [k (range 1 6)
                :let [rho (/ (autocovariance xs k) g0)
                      z (/ (- rho (nth acf k)) (/ (nth acf-se-sqrt-n (dec k)) (m/sqrt n)))]]
          (is (< (m/abs z) 4.0) (str "acf lag " k " z " z " sample " rho " theory " (nth acf k))))))))

