(defn- ex-data-of
  "`ex-data` of the `ex-info` thrown by `f`, `::other` for another exception, `nil` when nothing is thrown."
  [f]
  (try (f) nil
       (catch clojure.lang.ExceptionInfo e (or (ex-data e) {}))
       (catch Throwable _ ::other)))

(defn- invalid-input?
  "True when `f` throws `ex-info` of the type `:invalid-input` with the given `:property`."
  [property f]
  (let [data (ex-data-of f)]
    (and (map? data) (= :invalid-input (:type data)) (= property (:property data)))))

(defn- ex-info? [f] (map? (ex-data-of f)))

(defn- max-abs-diff
  "Maximum absolute difference of two sequences of the same length (`##Inf` for different lengths)."
  ^double [xs ys]
  (if (= (count xs) (count ys))
    (reduce (fn [^double mx [a b]] (m/max mx (m/abs (- (double a) (double b))))) 0.0 (map vector xs ys))
    Double/POSITIVE_INFINITY))

(defn- close-all?
  "Every element of `xs` is within `tol * max(1, |y|)` of `ys` (and the lengths are equal)."
  [xs ys tol]
  (and (= (count xs) (count ys))
       (every? true? (map (fn [a b] (<= (m/abs (- (double a) (double b))) (* (double tol) (m/max 1.0 (m/abs (double b)))))) xs ys))))

(defn- series
  "The process of the coefficients `phi` and `theta` (vectors, either may be empty) with `ma`, `ar` or `arma`."
  ([phi theta signal] (series phi theta signal nil))
  ([phi theta signal opts]
   (cond
     (and (seq phi) (seq theta)) (if opts (r/arma phi theta signal opts) (r/arma phi theta signal))
     (seq phi) (if opts (r/ar phi signal opts) (r/ar phi signal))
     :else (if opts (r/ma theta signal opts) (r/ma theta signal)))))

(defn- series-with-default-signal
  [phi theta opts]
  (cond
    (and (seq phi) (seq theta)) (r/arma phi theta opts)
    (seq phi) (r/ar phi opts)
    :else (r/ma theta opts)))

(def ^:private sig
  "The signal of the reference (N = 120)."
  (delay (:signal @reference)))

