(ns fastmath.random.series-test
  "Tests of the time series generators of `fastmath.random`: `white-noise`, `ma`, `ar`, `arma`, `fi`, `arfima` (Random Audit,
  work packages 4.1-4.8, 9.5).

  Oracles (`test/resources/random/series_reference.edn`, generated by `utils/fastmath/dev/generate_random_series_reference.{py,R}`):
  - `scipy.signal.lfilter` (zero initial conditions) for `ma` (exact, output j = filter value at signal index 2q + j), for the AR(1)
    (exact) and, asymptotically, for the raw-seeded AR(p >= 2) / ARMA start (the difference decays below 1e-6 by output 60);
  - an independent Python emulation of the library recursion (history seeded with the first cnt signal values, recursion from index
    cnt, `burn-in` outputs dropped, default cnt) checked exactly (1e-13), including the burn-in variants;
  - R `stats::arima.sim` with explicit `innov`, `start.innov` and `n.start = 2 (p + q)`;
  - mpmath (50 digits) for the psi weights `psi_k = Gamma(k+d) / (Gamma(d) k!)` of the exact `fi` and for the coefficients of
    `fi-diffs` (`binomial`); numpy `cumsum` / `np.diff(prepend=0)` for the integer `fi`;
  - statsmodels `ArmaProcess` for the variance and the acf of four ARMA models with Bartlett standard errors.
  The seeded outputs of the code before the audit are in `test/resources/random/baseline_reference.edn` (`:series`)."
  (:require [clojure.edn :as edn]
            [clojure.java.io :as io]
            [clojure.test :refer [deftest is testing]]
            [fastmath.core :as m]
            [fastmath.random :as r]))

