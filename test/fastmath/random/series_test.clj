(deftest fi-integer-vs-numpy
  (is (= #{1 2 3 -1 -2} (set (keys (:fi-int @reference)))))
  (doseq [[d expected] (:fi-int @reference)
          :let [k (long (m/abs (long d)))
                actual (vec (r/fi d (take 60 @sig)))]]
    (testing (str "d = " d)
      (is (= (- 60 (* 2 k)) (count actual)) "N - 2|d|")
      ;; numpy: d-fold cumsum / np.diff(prepend=0); offset 2|d|; relative tolerance (cumsum^3 grows like t^2)
      (is (close-all? actual (drop (* 2 k) expected) 1.0e-10) (str "max diff " (max-abs-diff actual (drop (* 2 k) expected)))))))

(deftest fi-integer-closed-forms
  (testing "d-fold cumulative sum: y_t = sum_s C(t - s + d - 1, d - 1) e_s (exact BigDecimal arithmetic)"
    (doseq [d [2 3 5]
            :let [e (vec (take 40 @sig))
                  expected (for [t (range (* 2 d) 40)]
                             (double (reduce + 0M (for [s (range (inc t))]
                                                    (* (bigdec (nth e s))
                                                       (bigdec (reduce (fn [^java.math.BigInteger acc i] (.divide (.multiply acc (biginteger (+ (- t s) i 1)))
                                                                                                                  (biginteger (inc i))))
                                                                       (biginteger 1) (range (dec d)))))))))
                  actual (vec (r/fi d e))]]
      (is (close-all? actual expected 1.0e-10) (str "d = " d))))
  (testing "d = 100: the 100-fold cumulative sum (first output at t = 200), the exponents of the growth are exact"
    (let [e (vec (take 205 (cycle [1.0])))
          out (vec (r/fi 100 e))]
      (is (= 5 (count out)))
      ;; for ones the 100-fold cumsum at t is C(t + 100, 100)
      (is (every? true? (map (fn [t o] (let [exact (double (reduce (fn [^java.math.BigInteger acc i]
                                                                      (.divide (.multiply acc (biginteger (+ t 1 i))) (biginteger (inc i))))
                                                                    (biginteger 1) (range 100)))]
                                         (<= (m/abs (- o exact)) (* 1.0e-12 exact))))
                             (range 200 205) out))))
    (is (= 5 (count (r/fi -100 (repeat 205 1.0)))))
    (is (= [0.0 0.0 0.0] (vec (take 3 (r/fi -100 (repeat 205 1.0))))) "the 100th difference of a constant is 0")))

