(defn- used-heap-after-gc
  "Used heap in bytes after (best effort) garbage collections."
  ^long []
  (let [rt (Runtime/getRuntime)]
    (dotimes [_ 4]
      (System/gc)
      (System/runFinalization)
      (Thread/sleep 30))
    (- (.totalMemory rt) (.freeMemory rt))))

(defn- heap-at-end
  "Consumes `n` elements of `coll` (which is not held) and returns the used heap after GC measured at the last element."
  ^long [coll ^long n]
  (let [result (volatile! -1)]
    (reduce (fn [^long i _] (when (== i (dec n)) (vreset! result (used-heap-after-gc))) (inc i)) 0 (take n coll))
    (long @result)))

(deftest memory-is-constant
  ;; Heap after GC at the last of 3 * 10^6 elements, compared with the run of the white noise alone (the same signal and the same
  ;; consumption). The memory of the old `(subvec (conj history x) 1)` grew by about 20 bytes per element and filter stage (measured
  ;; before the audit: +62 MB for `ar` and `ma`, +124 MB for `arma`); now the difference is 4 KB. The bound of 25 MB is generous
  ;; (GC jitter and the JVM configuration).
  (let [n 3000000
        limit (* 25 1024 1024)
        baseline-heap (heap-at-end (r/white-noise (r/rng :mersenne 1)) n)]
    (doseq [[nm mk] [["ar" #(r/ar 0.5 (r/white-noise (r/rng :mersenne 1)))]
                     ["ma" #(r/ma 0.5 (r/white-noise (r/rng :mersenne 1)))]
                     ["arma" #(r/arma 0.5 0.3 (r/white-noise (r/rng :mersenne 1)))]]
            :let [h (heap-at-end (mk) n)]]
      (is (<= (- h baseline-heap) limit) (str nm " heap growth " (quot (- h baseline-heap) 1024) " KB over the white noise baseline")))))

