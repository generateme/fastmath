(deftest hand-computed-examples
  (let [s (vec (range 1 11))]
    (testing "ar: Y0 = 1, Y1 = 2.5, Y2 = 4.25 (dropped: 2.5), then Y3 = 6.125"
      (is (= [4.25 6.125 8.0625] (vec (take 3 (r/ar 0.5 s)))))
      (is (= [4.25] (vec (r/ar 0.5 [1 2 3])))))
    (testing "ma: e2 + 0.5 e1 = 3 + 1"
      (is (= [4.0 5.5 7.0] (vec (take 3 (r/ma 0.5 s))))))
    (testing "ar [0.5 0.0] has two coefficients: 2 * 2 = 4 elements are dropped"
      (is (= [8.0 10.0 12.0] (vec (take 3 (r/ar [0.5 0.0] s)))))
      (is (= [7.0 8.5 10.0] (vec (take 3 (r/ma [0.5 0.0] s))))))
    (testing "arma: the ma output [4.0 5.5 7.0 ...] is the signal of ar"
      (let [x (vec (r/ma 0.5 s))]
        (is (= (vec (r/ar 0.5 x)) (vec (r/arma 0.5 0.5 s))))))
    (testing "integer fi (zero initial conditions)"
      (is (= [6.0 10.0 15.0] (vec (r/fi 1 (range 1 6)))) "cumsum 1 3 6 10 15, drop 2")
      (is (= [15.0 21.0 28.0] (vec (r/fi 2 (repeat 7 1.0)))) "cumsum^2 of ones 1 3 6 10 15 21 28, drop 4")
      (is (= [5.0 7.0 9.0] (vec (r/fi -1 [1 4 9 16 25]))) "diff 1 3 5 7 9, drop 2")
      (is (= [2.0 2.0] (vec (r/fi -2 [1 4 9 16 25 36]))) "diff^2 1 2 2 2 2 2, drop 4")
      (is (= [1 4 9] (vec (r/fi 0 [1 4 9]))) "d = 0 is the identity"))
    (testing "exact fi d = 0.5: psi_k = C(2k, k) / 4^k = 1 0.5 0.375 0.3125; the seed is not emitted"
      (is (= [0.5 0.375 0.3125] (vec (r/fi 0.5 [1 0 0 0])))))
    (testing "truncated fi with one lag is an AR(1) with phi = d"
      (is (= (vec (r/ar 0.5 s)) (vec (r/fi 0.5 1 s))))
      (is (= (vec (r/ar 0.3 s)) (vec (r/fi 0.3 1 s)))))
    (testing "fi-diffs: c_1 = d, c_2 = d (1 - d) / 2"
      (is (= [0.5 0.125] (fi-diffs 0.5 2)))
      (is (= [] (fi-diffs 0.5 0))))))

