(deftest emulation-of-the-library-recursion
  (testing "N = 40 and N = 120: the output equals the emulation of the raw-seeded recursion (1e-13)"
    (is (= 14 (count (:filters @reference))))
    (doseq [{:keys [id phi theta emulation]} (:filters @reference)
            n [40 120]
            :let [out (series phi theta (take n @sig))
                  cnt (+ (count phi) (count theta))]]
      (is (= (- n (* 2 cnt)) (count out)) (str id " length"))
      (is (< (max-abs-diff out (take (count out) emulation)) 1.0e-13) (str id " N = " n))))
  (testing "the same through arma with empty parts"
    (doseq [{:keys [id phi theta emulation]} (:filters @reference)]
      (is (< (max-abs-diff (r/arma phi theta (take 120 @sig)) emulation) 1.0e-13) (str id)))))

(deftest ma-and-ar1-are-the-lfilter-output
  (testing "ma: output j = lfilter([1 theta], [1], e)[2q + j], exact; ar(1): lfilter([1], [1 -phi], e)[2 + j]"
    (doseq [{:keys [id phi theta lfilter]} (:filters @reference)
            :when (or (empty? phi) (and (= 1 (count phi)) (empty? theta)))
            n [40 120]
            :let [cnt (+ (count phi) (count theta))
                  out (series phi theta (take n @sig))]]
      ;; observed max difference 4.4e-16
      (is (< (max-abs-diff out (take (count out) (drop (* 2 cnt) lfilter))) 1.0e-13) (str id " N = " n))))
  (testing "order 1-4 are covered"
    (let [orders (fn [k] (set (map #(count (k %)) (filter #(empty? ((if (= k :phi) :theta :phi) %)) (:filters @reference)))))]
      (is (= #{1 2 3 4} (orders :phi)))
      (is (= #{1 2 3 4} (orders :theta))))))

(deftest raw-seeded-start-is-not-the-zero-initial-condition-filter
  (let [tail-from 60
        rows (for [{:keys [id phi theta lfilter]} (:filters @reference)
                   :when (and (pos? (count phi)) (not (and (= 1 (count phi)) (empty? theta))))
                   :let [cnt (+ (count phi) (count theta))
                         out (series phi theta @sig)
                         diffs (map (fn [a b] (m/abs (- (double a) (double b)))) out (drop (* 2 cnt) lfilter))]]
               [id (first diffs) (apply max (drop tail-from diffs))])]
    (is (= 9 (count rows)))
    (doseq [[id first-diff tail-diff] rows]
      ;; first-diff observed 0.015 (arma-22) ... 0.32 (arma-11); tail-diff observed <= 3.0e-7 (arma-44)
      (is (> first-diff 1.0e-3) (str id " the start differs from the zero-IC filter: " first-diff))
      (is (< tail-diff 1.0e-6) (str id " the difference decays: " tail-diff)))))

(deftest r-arima-sim
  (testing "ma(q) and ar(1) equal arima.sim with innov, start.innov and n.start = 2 (p + q) (observed 4.4e-16)"
    (doseq [{:keys [id phi theta arima-sim]} (:filters @reference)
            :when (or (empty? phi) (and (= 1 (count phi)) (empty? theta)))
            :let [out (series phi theta @sig)]]
      (is (= 120 (+ (count out) (* 2 (+ (count phi) (count theta))))))
      (is (< (max-abs-diff out arima-sim) 1.0e-13) (str id))))
  (testing "ar(p >= 2) and arma: R starts from zero initial conditions, the difference is a decaying transient"
    (doseq [{:keys [id phi theta arima-sim]} (:filters @reference)
            :when (and (seq phi) (not (and (= 1 (count phi)) (empty? theta))))
            :let [out (series phi theta @sig)
                  diffs (map (fn [a b] (m/abs (- (double a) (double b)))) out arima-sim)]]
      (is (= (count out) (count arima-sim)))
      (is (> (first diffs) 1.0e-3) (str id))
      ;; observed tail (output >= 60) max 1.9e-7 (arma-44)
      (is (< (apply max (drop 60 diffs)) 1.0e-6) (str id)))))

(deftest burn-in-variants
  (is (= 20 (count (:burn-in @reference))))
  (doseq [{:keys [id burn-in emulation]} (:burn-in @reference)
          :let [{:keys [phi theta]} (first (filter #(= id (:id %)) (:filters @reference)))
                out (series phi theta @sig {:burn-in burn-in})
                p (count phi)
                q (count theta)
                stages (if (and (seq phi) (seq theta)) 2 1)]]
    (testing (str id " burn-in " burn-in)
      (is (< (max-abs-diff out emulation) 1.0e-13))
      (is (= (- 120 p q (* stages burn-in)) (count out)) "N - p - q - burn-in per stage"))))

(deftest burn-in-lengths-and-boundaries
  (let [s (vec (range 1 21))]
    (testing "burn-in 0 returns N - cnt elements, the first output is the first recursion step"
      (is (= 19 (count (r/ar [0.5] s {:burn-in 0}))))
      (is (= 19 (count (r/ma [0.5] s {:burn-in 0}))))
      (is (= 18 (count (r/ar [0.5 0.2] s {:burn-in 0}))))
      (is (= 16 (count (r/ar [0.5 0.2 0.1 0.05] s {:burn-in 0}))))
      (is (= 18 (count (r/arma [0.5] [0.3] s {:burn-in 0}))) "N - p - q")
      ;; Y0 = 1 (seed), Y1 = 0.5 * 1 + 2
      (is (= [2.5 4.25 6.125] (vec (take 3 (r/ar 0.5 s {:burn-in 0})))))
      ;; MA(1): e1 + 0.5 e0 = 2.5, e2 + 0.5 e1 = 4
      (is (= [2.5 4.0 5.5] (vec (take 3 (r/ma 0.5 s {:burn-in 0}))))))
    (testing "the default burn-in is cnt: {:burn-in cnt} equals the default"
      (doseq [cnt [1 2 4]
              :let [c (vec (repeat cnt 0.1))]]
        (is (= (vec (r/ar c s)) (vec (r/ar c s {:burn-in cnt}))))
        (is (= (vec (r/ma c s)) (vec (r/ma c s {:burn-in cnt}))))
        (is (= (vec (r/arma c c s)) (vec (r/arma c c s {:burn-in cnt}))))
        (is (= (vec (r/ar c s)) (vec (r/ar c s {:burn-in nil}))) "nil = default")))
    (testing "burn-in k: the same as dropping k more elements of the burn-in 0 output"
      (doseq [k [0 1 3 7]]
        (is (= (vec (drop k (r/ar [0.5 0.2] s {:burn-in 0}))) (vec (r/ar [0.5 0.2] s {:burn-in k}))))
        (is (= (vec (drop k (r/ma [0.5 0.2] s {:burn-in 0}))) (vec (r/ma [0.5 0.2] s {:burn-in k}))))))
    (testing "a large burn-in gives an empty sequence, no exception"
      (doseq [k [20 21 1000 Integer/MAX_VALUE Long/MAX_VALUE]]
        (is (empty? (r/ar [0.5] s {:burn-in k})))
        (is (empty? (r/ma [0.5] s {:burn-in k})))
        (is (empty? (r/arma [0.5] [0.5] s {:burn-in k}))))
      (doseq [k [20 21 1000 Integer/MAX_VALUE]]
        (is (empty? (r/fi 0.3 5 s {:burn-in k})))
        (is (empty? (r/fi 2 s {:burn-in k})))
        (is (empty? (r/fi -2 s {:burn-in k})))
        (is (empty? (r/arfima [0.5] 0.3 4 [0.3] s {:burn-in k})))))
    (testing "burn-in is applied to every stage of arma and arfima"
      (is (= 12 (count (r/arma [0.5] [0.3] s {:burn-in 3}))) "20 - 1 - 1 - 2 * 3")
      (is (= 8 (count (r/arfima [0.5] 0.3 4 [0.3] s {:burn-in 2}))) "20 - (1 + 2) - (4 + 2) - (1 + 2)")
      (is (= 13 (count (r/arfima [0.5] 2 0 [0.3] s {:burn-in 1}))) "integer d: 20 - (1 + 1) - (2 + 1) - (1 + 1)"))))

