;;

;; `K`/`E` reference values below were computed with Python (scipy) over a
;; large negative-argument sample (`negx`) and a dense sweep from -2.0 to
;; ~1.0 (`sweep`, used by both `ellipk` and `ellipe`). They are stored, along
;; with their input grids and comparison tolerances, in
;; `test/resources/special/ellip_reference.edn` to keep this file readable.

(def ^:private ellip-reference
  (delay (edn/read-string (slurp (io/resource "special/ellip_reference.edn")))))

(t/deftest negx
  (let [{:keys [arg K E]} (:negx @ellip-reference)]
    (t/testing "ellip-K"
      (t/is (v/delta-eq (v/fmap arg sut/K) (:ref K) (:tol K))))
    (t/testing "ellip-E"
      (t/is (v/delta-eq (v/fmap arg sut/E) (:ref E) (:tol E))))))

;;

(t/deftest ellipk
  (let [{:keys [arg K]} (:sweep @ellip-reference)]
    (t/is (v/edelta-eq (v/fmap arg sut/K) (:ref K) (:tol K)))))

(t/deftest ellipe
  (let [{:keys [arg E]} (:sweep @ellip-reference)]
    (t/is (v/edelta-eq (v/fmap arg sut/E) (:ref E) (:tol E)))))
