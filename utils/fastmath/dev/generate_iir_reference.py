"""Generator of reference values for `fastmath.signal.iir-test`.

Produces `test/resources/signal/iir_reference.edn` with `scipy.signal` results:
impulse responses (80 samples, `sosfilt`) and frequency responses (`sosfreqz`
at k fs / 32, k = 0..15) of Butterworth, Chebyshev I/II and Bessel
(`norm='phase'`) designs for every kind; band filters use the band
`cutoff +- bandwidth/2`. Cookbook biquads (impulse response, `lfilter`) with
coefficients from the cookbook formulas (digital bandwidth).

Run from anywhere:
    cd /home/ts/penv && uv run python \
        /home/ts/clojure/fastmath/utils/fastmath/dev/generate_iir_reference.py
"""
from pathlib import Path

import numpy as np
import scipy.signal as ss

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "test" / "resources" / "signal" / "iir_reference.edn"


def f(x):
    return repr(float(x))


def vec(xs):
    return "[" + " ".join(f(x) for x in xs) + "]"


def cvec(zs):
    return "[" + " ".join("[%s %s]" % (f(z.real), f(z.imag)) for z in zs) + "]"


impulse = np.zeros(80)
impulse[0] = 1.0
entries = []
for fs, cutoff, bandwidth in [(1.0, 0.1, 0.1), (1000.0, 120.0, 60.0)]:
    for kind in ["lowpass", "highpass", "bandpass", "bandstop"]:
        wn = cutoff if kind in ("lowpass", "highpass") else [cutoff - bandwidth / 2, cutoff + bandwidth / 2]
        for design, order, extra in [("butterworth", 4, {}), ("butterworth", 5, {}),
                                     ("chebyshev", 4, {"type": "type-I", "ripple": 1.0}),
                                     ("chebyshev", 4, {"type": "type-II", "ripple": 40.0}),
                                     ("bessel", 4, {})]:
            if design == "butterworth":
                sos = ss.butter(order, wn, kind, fs=fs, output="sos")
            elif design == "bessel":
                sos = ss.bessel(order, wn, kind, fs=fs, output="sos", norm="phase")
            elif extra["type"] == "type-I":
                sos = ss.cheby1(order, extra["ripple"], wn, kind, fs=fs, output="sos")
            else:
                sos = ss.cheby2(order, extra["ripple"], wn, kind, fs=fs, output="sos")
            _, h = ss.sosfreqz(sos, worN=np.arange(16) * fs / 32, fs=fs)
            opts = " ".join(":%s %s" % (k, (":" + v) if isinstance(v, str) else f(v)) for k, v in extra.items())
            entries.append("{:design :%s :kind :%s :order %d :fs %s :cutoff %s :bandwidth %s %s :impulse %s :response %s}"
                           % (design, kind, order, f(fs), f(cutoff), f(bandwidth), opts,
                              vec(ss.sosfilt(sos, impulse)), cvec(h)))

biquads = []
fs, fc, bw = 44100.0, 1000.0, 1.0
w0 = 2 * np.pi * fc / fs
c = np.cos(w0)
al = np.sin(w0) * np.sinh(np.log(2) / 2 * bw * w0 / np.sin(w0))
for kind, b, a in [("lowpass", [(1 - c) / 2, 1 - c, (1 - c) / 2], [1 + al, -2 * c, 1 - al]),
                   ("highpass", [(1 + c) / 2, -(1 + c), (1 + c) / 2], [1 + al, -2 * c, 1 - al]),
                   ("bandpass", [al, 0.0, -al], [1 + al, -2 * c, 1 - al]),
                   ("notch", [1.0, -2 * c, 1.0], [1 + al, -2 * c, 1 - al]),
                   ("allpass", [1 - al, -2 * c, 1 + al], [1 + al, -2 * c, 1 - al])]:
    biquads.append("{:kind :%s :cutoff %s :fs %s :bandwidth %s :impulse %s}"
                   % (kind, f(fc), f(fs), f(bw), vec(ss.lfilter(b, a, impulse))))

OUT.parent.mkdir(parents=True, exist_ok=True)
with open(OUT, "w") as fo:
    fo.write(";; generated by utils/fastmath/dev/generate_iir_reference.py\n")
    fo.write("{:designs [" + "\n ".join(entries) + "]\n :biquads [" + "\n ".join(biquads) + "]}\n")

print("designs:", len(entries), "biquads:", len(biquads))
print("wrote", OUT)
