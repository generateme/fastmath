;; Benchmark of fastmath.calculus.autodiff (forward-mode AD) against fastmath.calculus finite differences.
;;
;; Run in a fresh JVM (preferred, a long running REPL gives noisy and megamorphic call sites), criterium on the
;; classpath (criterium 0.4.6 comes from the ~/.lein/profiles.clj user profile):
;;
;;   lein classpath > /tmp/fastmath-cp.txt
;;   java -cp "$(cat /tmp/fastmath-cp.txt)" clojure.main utils/fastmath/dev/autodiff_bench.clj
;;
;; Add -Dautodiff.bench.skip-univariate=true (before -cp) to run only the multivariate part.
;; From a REPL: (load-file "utils/fastmath/dev/autodiff_bench.clj")
;;
;; For each function and order 1-3 it reports the mean time per call (criterium quick-benchmark) of:
;; the plain primitive function (fastmath.core ops), the AD derivative, the finite-difference derivative
;; (central, accuracy 2, automatic step), and the absolute error of both derivatives against ForwardDiff.jl
;; (test/resources/calculus/autodiff_reference.edn, generated by generate_autodiff_reference.jl).
;;
;; The multivariate part compares ad/gradient, ad/jacobian, ad/hessian (default chunking) with calc/gradient,
;; calc/jacobian, calc/hessian (central differences, automatic step) for a sparse (chained Rosenbrock) and a dense
;; function. Finite differences are timed twice: on the autodiff function called with plain doubles ("FD ad f",
;; protocol dispatch and boxing) and on an equivalent primitive function ("FD prim f", fastmath.core ops), which is
;; the fair baseline; as in the univariate part. The error is the maximum absolute difference to ForwardDiff.jl
;; (autodiff_multivariate_reference.edn) where a reference exists. A chunk-size sweep of the hessian follows.

(ns fastmath.dev.autodiff-bench
  (:require [criterium.core :as crit]
            [clojure.edn :as edn]
            [clojure.java.io :as io]
            [fastmath.core :as m]
            [fastmath.calculus :as calc]
            [fastmath.calculus.autodiff :as ad]))

(def cases
  "id, point (present in the reference file), primitive function, the same function built from autodiff ops"
  [[:poly 0.7
    (fn ^double [^double x] (m/+ (m/* 3.0 (m/pow x 4.0)) (m/* -2.0 (m/pow x 3.0)) x -5.0))
    (fn [x] (ad/+ (ad/* 3.0 (ad/pow x 4.0)) (ad/* -2.0 (ad/pow x 3.0)) x -5.0))]
   [:exp-sin 0.7
    (fn ^double [^double x] (m/* (m/exp x) (m/sin x)))
    (fn [x] (ad/* (ad/exp x) (ad/sin x)))]
   [:log-pow 1.0
    (fn ^double [^double x] (m/log (m/+ (m/pow x 2.5) 1.0)))
    (fn [x] (ad/log (ad/+ (ad/pow x 2.5) 1.0)))]])

(def reference (edn/read-string (slurp (io/resource "calculus/autodiff_reference.edn"))))

(defn reference-value [id ^double x ^long n]
  (let [{xs :x :as r} (reference id)
        i (.indexOf ^java.util.List xs x)]
    (nth (r (keyword (str "d" n))) i)))

(defn mean-ns
  "Mean time of one call of `thunk` in nanoseconds."
  ^double [thunk]
  (m/* 1.0e9 (double (first (:mean (crit/quick-benchmark* thunk {}))))))

(defn run []
  (println "| function | order | plain f [ns] | AD [ns] | FD [ns] | AD/FD | AD abs error | FD abs error |")
  (println "|---|---|---|---|---|---|---|---|")
  (doseq [[id x f f-ad] cases
          :let [x (double x)
                t-plain (mean-ns (fn [] (f x)))]
          n [1 2 3]
          :let [d-ad (ad/derivative f-ad n)
                d-fd (calc/derivative f n)
                t-ad (mean-ns (fn [] (d-ad x)))
                t-fd (mean-ns (fn [] (d-fd x)))
                expected (double (reference-value id x n))]]
    (println (format "| %s | %d | %.1f | %.1f | %.1f | %.2f | %.2e | %.2e |"
                     (name id) n t-plain t-ad t-fd (m// t-ad t-fd)
                     (m/abs (m/- (double (d-ad x)) expected))
                     (m/abs (m/- (double (d-fd x)) expected))))))

(def multivariate-reference
  (edn/read-string (slurp (io/resource "calculus/autodiff_multivariate_reference.edn"))))

(def scalar-functions
  {:rosen (fn [v] (reduce ad/+ 0.0 (map (fn [a b] (ad/+ (ad/* 100.0 (ad/pow (ad/- b (ad/pow a 2.0)) 2.0))
                                                         (ad/pow (ad/- 1.0 a) 2.0))) v (rest v))))
   :dense (fn [v] (let [s (reduce ad/+ 0.0 v)
                        q (reduce ad/+ 0.0 (map (fn [a] (ad/* a a)) v))]
                    (reduce ad/+ 0.0 (map (fn [a] (ad/* (ad/sin (ad/* a s)) (ad/exp (ad// q 100.0)))) v))))})

(def vector-functions
  {:vec32 (fn [[x y z]] [(ad/* x y (ad/sin z)) (ad// (ad/exp x) (ad/+ 1.0 (ad/pow y 2.0) (ad/pow z 2.0)))])
   :vec23 (fn [[x y]] [(ad// x y) (ad/log (ad/+ x (ad/pow y 2.0))) (ad/pow x y)])})

(def primitive-scalar-functions
  {:rosen (fn ^double [v]
            (let [^doubles a (double-array v)
                  n (alength a)]
              (loop [i 0 s 0.0]
                (if (m/< i (m/dec n))
                  (let [ai (aget a i)
                        d (m/- (aget a (m/inc i)) (m/* ai ai))
                        e (m/- 1.0 ai)]
                    (recur (m/inc i) (m/+ s (m/* 100.0 d d) (m/* e e))))
                  s))))
   :dense (fn ^double [v]
            (let [^doubles a (double-array v)
                  n (alength a)
                  s (double (loop [i 0 s 0.0] (if (m/< i n) (recur (m/inc i) (m/+ s (aget a i))) s)))
                  q (double (loop [i 0 q 0.0] (if (m/< i n) (recur (m/inc i) (m/+ q (m/* (aget a i) (aget a i)))) q)))
                  e (m/exp (m// q 100.0))]
              (loop [i 0 r 0.0] (if (m/< i n) (recur (m/inc i) (m/+ r (m/* (m/sin (m/* (aget a i) s)) e))) r))))})

(def primitive-vector-functions
  {:vec32 (fn [[^double x ^double y ^double z]] [(m/* x y (m/sin z)) (m// (m/exp x) (m/+ 1.0 (m/* y y) (m/* z z)))])
   :vec23 (fn [[^double x ^double y]] [(m// x y) (m/log (m/+ x (m/* y y))) (m/pow x y)])})

(defn point [^long n] (mapv (fn [^long i] (m/- (m/* 0.3 (double i)) 0.8)) (range 1 (m/inc n))))

(defn max-abs-error [expected actual]
  (if expected
    (reduce m/max 0.0 (map (fn [e a] (m/abs (m/- (double e) (double a)))) (flatten expected) (flatten actual)))
    ##NaN))

(defn reference-entry [kind id x]
  (first (filter #(= x (:x %)) (get-in multivariate-reference [kind id]))))

(defn run-multivariate []
  (println)
  (println "| op | function | n | AD [us] | FD ad f [us] | FD prim f [us] | AD / FD prim f | AD abs error | FD prim f abs error |")
  (println "|---|---|---|---|---|---|---|---|---|")
  (doseq [[op ad-op fd-op key] [[:gradient ad/gradient calc/gradient :gradient]
                                [:hessian ad/hessian calc/hessian :hessian]]
          [id f] scalar-functions
          n [2 10 50]
          :let [x (point n)
                d-ad (ad-op f)
                d-fd (fd-op f)
                d-fdp (fd-op (primitive-scalar-functions id))
                expected (key (reference-entry :scalar id x))
                t-ad (mean-ns (fn [] (d-ad x)))
                t-fd (mean-ns (fn [] (d-fd x)))
                t-fdp (mean-ns (fn [] (d-fdp x)))]]
    (println (format "| %s | %s | %d | %.1f | %.1f | %.1f | %.2f | %.2e | %.2e |" (name op) (name id) n
                     (m// t-ad 1000.0) (m// t-fd 1000.0) (m// t-fdp 1000.0) (m// t-ad t-fdp)
                     (max-abs-error expected (d-ad x)) (max-abs-error expected (d-fdp x)))))
  (doseq [[id f] vector-functions
          {:keys [x jacobian]} (get-in multivariate-reference [:vector id])
          :let [d-ad (ad/jacobian f)
                d-fd (calc/jacobian f)
                d-fdp (calc/jacobian (primitive-vector-functions id))
                t-ad (mean-ns (fn [] (d-ad x)))
                t-fd (mean-ns (fn [] (d-fd x)))
                t-fdp (mean-ns (fn [] (d-fdp x)))]]
    (println (format "| jacobian | %s | %d | %.1f | %.1f | %.1f | %.2f | %.2e | %.2e |" (name id) (count x)
                     (m// t-ad 1000.0) (m// t-fd 1000.0) (m// t-fdp 1000.0) (m// t-ad t-fdp)
                     (max-abs-error jacobian (d-ad x)) (max-abs-error jacobian (d-fdp x)))))
  (println)
  (println "| hessian chunk size (n=10) | rosen [us] | dense [us] |")
  (println "|---|---|---|")
  (doseq [k [1 2 5 10]]
    (let [x (point 10)
          ts (map (fn [f] (let [h (ad/hessian f {:chunk-size k})] (m// (mean-ns (fn [] (h x))) 1000.0)))
                  [(:rosen scalar-functions) (:dense scalar-functions)])]
      (println (format "| %d | %.1f | %.1f |" k (first ts) (second ts))))))

(when-not (System/getProperty "autodiff.bench.skip-univariate") (run))
(run-multivariate)
