# Generator of statsmodels reference values for the regression audit: the links
# which R does not have (loglog, clog = log(1 - mu)).
#
# Writes test/resources/regression/statsmodels_reference.edn
# Run from the repository root:
#   cd /home/ts/penv && uv run python -I /path/to/fastmath/utils/fastmath/dev/regression_audit_ref_gen.py /path/to/fastmath
#
# Needs statsmodels (checked with 0.15.0).
import sys
import numpy as np
import statsmodels
import statsmodels.api as sm
from statsmodels.genmod.families import links

root = sys.argv[1] if len(sys.argv) > 1 else "."
x = np.arange(1, 9.0)
s = np.array([1, 2, 3, 5, 6, 8, 9, 9.0])
n = 10.0
X = sm.add_constant(x)


def num(v):
    v = float(v)
    if np.isnan(v):
        return "##NaN"
    if np.isinf(v):
        return "##Inf" if v > 0 else "##-Inf"
    return repr(v)


def vec(a):
    return "[" + " ".join(num(v) for v in a) + "]"


def fit(link):
    f = sm.GLM(np.column_stack([s, n - s]), X,
               family=sm.families.Binomial(link=link())).fit(tol=1e-14, maxiter=200)
    return ("{:intercept %s :beta %s :stderr %s :deviance %s :null-deviance %s :aic %s}"
            % (num(f.params[0]), vec(f.params[1:]), vec(f.bse), num(f.deviance),
               num(f.null_deviance), num(f.aic)))


out = ";; generated by utils/fastmath/dev/regression_audit_ref_gen.py, do not edit\n"
out += ";; statsmodels %s\n" % statsmodels.__version__
out += "{:data {:x %s :successes %s :failures %s}\n" % (vec(x), vec(s), vec(n - s))
out += " :binomial-loglog %s\n" % fit(links.LogLog)
out += " :binomial-cloglog %s\n" % fit(links.CLogLog)
out += " :binomial-clog %s}\n" % fit(links.LogC)
with open(root + "/test/resources/regression/statsmodels_reference.edn", "w") as fh:
    fh.write(out)
print("done")
