#
# Why: a third, independent implementation of agglomerative clustering. Clustering.jl uses the
# R merge encoding and order, so merges, heights and orders are compared directly.
# Linkages: :single, :complete, :average, :ward (= fastmath :ward, R ward.D2) and
# :ward_presquared (= fastmath :ward-d, R ward.D); Clustering.jl has no weighted, centroid or
# median linkage. Tie-free sets only. Datasets: the formulas of generate_hclust_reference.R.

using Clustering

const OUT = joinpath("test", "resources", "clustering", "hclust_julia_reference.edn")

x8 = [-0.626 0.576; 0.184 -0.305; -0.836 1.512; 1.595 0.39;
      0.33 -0.621; -0.82 -2.215; 0.487 1.125; 0.738 -0.045]
x30 = [round(sin(i * 1.3 + j * 2.1) * 3 + cos(i * j * 0.7), digits = 3) for i in 1:30, j in 1:3]

euclidean(x) = [sqrt(sum((x[i, :] .- x[j, :]) .^ 2)) for i in 1:size(x, 1), j in 1:size(x, 1)]

const METHODS = [("single", :single), ("complete", :complete), ("average", :average),
                 ("ward", :ward), ("ward-d", :ward_presquared)]

num(x) = repr(Float64(x))
vecs(xs, f) = "[" * join(f.(xs), " ") * "]"

function dataset(x)
    d = euclidean(x)
    entries = map(METHODS) do (name, l)
        h = hclust(d, linkage = l, branchorder = :r)
        merge = "[" * join(["[$(h.merges[i, 1]) $(h.merges[i, 2])]" for i in 1:size(h.merges, 1)], " ") * "]"
        ":$name {:merge $merge\n  :height $(vecs(h.heights, num))\n  :order $(vecs(h.order .- 1, string))}"
    end
    "{" * join(entries, "\n ") * "}"
end

open(OUT, "w") do io
    println(io, ";; generated by utils/fastmath/dev/generate_hclust_reference.jl, do not edit")
    println(io, "{:x8 " * dataset(x8) * "\n:x30 " * dataset(x30) * "}")
end
