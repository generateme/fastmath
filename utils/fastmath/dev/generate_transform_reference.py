"""Generator of reference values for `fastmath.transform-test`.

Produces `test/resources/transform/fourier_reference.edn` with numpy / scipy
results for every length in LENGTHS and every `norm`:

- `:rfft`, `:fft` (real input, single- and double-sided), `:cfft` (complex input),
  `:ifft` (inverse of the complex input treated as a spectrum),
- `:dct`, `:idct`, `:dst`, `:idst` for types 1-3 (`scipy.fft`; DCT-I needs N >= 2),
- `:dht` = Re(fft) - Im(fft), `:idht` = dht / N (with norm scaling),
- `:hadamard` (`scipy.linalg.hadamard @ x`, power-of-two lengths),
- 2d: `:rfft2`, `:fft2` (complex result as rows of [re im] pairs), `:dht2`.

Inputs are deterministic (seeded) and stored with the results.

Run from anywhere:
    cd /home/ts/penv && uv run python \
        /home/ts/clojure/fastmath/utils/fastmath/dev/generate_transform_reference.py
"""
from pathlib import Path

import numpy as np
import scipy.fft as sf
import scipy.linalg as sl

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "test" / "resources" / "transform" / "fourier_reference.edn"

LENGTHS = [1, 2, 3, 5, 8, 15, 16, 17]
NORMS = ["backward", "ortho", "forward"]
rng = np.random.default_rng(20261012)


def f(x):
    return repr(float(x))


def reals(xs):
    return "[" + " ".join(f(x) for x in xs) + "]"


def cplx(zs):
    return "[" + " ".join("[%s %s]" % (f(z.real), f(z.imag)) for z in zs) + "]"


def dht(x, norm):
    X = sf.fft(x, norm=norm)
    return X.real - X.imag


entries = []
for n in LENGTHS:
    x = np.round(rng.uniform(-5, 5, n), 6)
    z = np.round(rng.uniform(-5, 5, n), 6) + 1j * np.round(rng.uniform(-5, 5, n), 6)
    e = {":n": str(n), ":x": reals(x), ":z": cplx(z)}
    for norm in NORMS:
        k = ":" + norm
        res = {
            ":rfft": cplx(sf.rfft(x, norm=norm)),
            ":fft": cplx(sf.fft(x, norm=norm)),
            ":cfft": cplx(sf.fft(z, norm=norm)),
            ":ifft": cplx(sf.ifft(z, norm=norm)),
            ":dht": reals(dht(x, norm)),
            ":idht": reals(dht(x, norm) / n if norm == "backward"
                           else dht(x, norm) if norm == "ortho" else dht(x, "backward")),
        }
        for t in (1, 2, 3):
            if not (t == 1 and n < 2):
                res[":dct%d" % t] = reals(sf.dct(x, type=t, norm=norm))
                res[":idct%d" % t] = reals(sf.idct(x, type=t, norm=norm))
            res[":dst%d" % t] = reals(sf.dst(x, type=t, norm=norm))
            res[":idst%d" % t] = reals(sf.idst(x, type=t, norm=norm))
        e[k] = "{" + " ".join("%s %s" % kv for kv in res.items()) + "}"
    if n & (n - 1) == 0:
        e[":hadamard"] = reals(sl.hadamard(n) @ x)
    entries.append("{" + " ".join("%s %s" % kv for kv in e.items()) + "}")

entries2d = []
for rows, cols in [(4, 6), (5, 3), (1, 4), (3, 1)]:
    x = np.round(rng.uniform(-5, 5, (rows, cols)), 6)
    X = sf.fft2(x)
    entries2d.append("{:rows %d :cols %d :x [%s] :rfft2 [%s] :fft2 [%s] :dht2 [%s]}"
                     % (rows, cols,
                        " ".join(reals(r) for r in x),
                        " ".join(cplx(r) for r in sf.rfft2(x)),
                        " ".join(cplx(r) for r in X),
                        " ".join(reals(r) for r in (X.real - X.imag))))

OUT.parent.mkdir(parents=True, exist_ok=True)
with open(OUT, "w") as fo:
    fo.write(";; generated by utils/fastmath/dev/generate_transform_reference.py (numpy %s, scipy)\n" % np.__version__)
    fo.write("{:one-d [" + "\n ".join(entries) + "]\n :two-d [" + "\n ".join(entries2d) + "]}\n")

print("lengths:", LENGTHS, "2d cases:", len(entries2d))
print("wrote", OUT)
