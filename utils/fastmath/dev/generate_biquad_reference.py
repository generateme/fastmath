"""Generator of reference values for `fastmath.signal.biquad-test`.

Produces `test/resources/signal/biquad_reference.edn`: biquad coefficients
written independently from the Audio EQ Cookbook (R. Bristow-Johnson,
https://webaudio.github.io/Audio-EQ-Cookbook/Audio-EQ-Cookbook.txt), digital
bandwidth form `alpha = sin(w0) sinh(ln2/2 BW w0/sin(w0))`, shelves with
`alpha = sin(w0)/(2Q)` and `Q` from the shelf slope
`1/Q = sqrt((A + 1/A)(1/S - 1) + 2)`.

Each entry: `[b0 b1 b2 a0 a1 a2]` with b's, a1, a2 divided by a0 (a0 raw).

Run from anywhere:
    cd /home/ts/penv && uv run python \
        /home/ts/clojure/fastmath/utils/fastmath/dev/generate_biquad_reference.py
"""
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "test" / "resources" / "signal" / "biquad_reference.edn"


def norm(b0, b1, b2, a0, a1, a2):
    return [b0 / a0, b1 / a0, b2 / a0, a0, a1 / a0, a2 / a0]


def band_alpha(w0, bw):
    return np.sin(w0) * np.sinh(np.log(2) / 2 * bw * w0 / np.sin(w0))


def coeffs(kind, fc, fs, bw=None, gain=None, Q=None):
    w0 = 2 * np.pi * fc / fs
    c, s = np.cos(w0), np.sin(w0)
    if kind in ("lowpass", "highpass", "bandpass", "notch", "allpass", "equalizer"):
        al = band_alpha(w0, bw)
    if kind == "lowpass":
        return norm((1 - c) / 2, 1 - c, (1 - c) / 2, 1 + al, -2 * c, 1 - al)
    if kind == "highpass":
        return norm((1 + c) / 2, -(1 + c), (1 + c) / 2, 1 + al, -2 * c, 1 - al)
    if kind == "bandpass":
        return norm(al, 0.0, -al, 1 + al, -2 * c, 1 - al)
    if kind == "notch":
        return norm(1.0, -2 * c, 1.0, 1 + al, -2 * c, 1 - al)
    if kind == "allpass":
        return norm(1 - al, -2 * c, 1 + al, 1 + al, -2 * c, 1 - al)
    A = 10 ** (gain / 40)
    if kind == "equalizer":
        return norm(1 + al * A, -2 * c, 1 - al * A, 1 + al / A, -2 * c, 1 - al / A)
    al = s / (2 * Q)
    sa = 2 * np.sqrt(A) * al
    if kind == "lowshelf":
        return norm(A * ((A + 1) - (A - 1) * c + sa), 2 * A * ((A - 1) - (A + 1) * c),
                    A * ((A + 1) - (A - 1) * c - sa), (A + 1) + (A - 1) * c + sa,
                    -2 * ((A - 1) + (A + 1) * c), (A + 1) + (A - 1) * c - sa)
    if kind == "highshelf":
        return norm(A * ((A + 1) + (A - 1) * c + sa), -2 * A * ((A - 1) + (A + 1) * c),
                    A * ((A + 1) + (A - 1) * c - sa), (A + 1) - (A - 1) * c + sa,
                    2 * ((A - 1) - (A + 1) * c), (A + 1) - (A - 1) * c - sa)


def f(x):
    return repr(float(x))


entries = []
for fs in (44100.0, 48000.0, 1.0):
    for fc in (fs * 0.001, fs * 0.05, fs * 0.2, fs * 0.45):
        for bw in (0.3, 1.0, 2.0):
            for kind in ("lowpass", "highpass", "bandpass", "notch", "allpass"):
                entries.append("{:kind :%s :fc %s :fs %s :bw %s :coeffs [%s]}"
                               % (kind, f(fc), f(fs), f(bw), " ".join(f(x) for x in coeffs(kind, fc, fs, bw=bw))))
            for gain in (-12.0, 0.0, 6.0):
                entries.append("{:kind :equalizer :fc %s :fs %s :bw %s :gain %s :coeffs [%s]}"
                               % (f(fc), f(fs), f(bw), f(gain),
                                  " ".join(f(x) for x in coeffs("equalizer", fc, fs, bw=bw, gain=gain))))
        for Q in (0.5, 0.7071, 2.0):
            for gain in (-12.0, 0.0, 6.0):
                for kind in ("lowshelf", "highshelf"):
                    entries.append("{:kind :%s :fc %s :fs %s :Q %s :gain %s :coeffs [%s]}"
                                   % (kind, f(fc), f(fs), f(Q), f(gain),
                                      " ".join(f(x) for x in coeffs(kind, fc, fs, gain=gain, Q=Q))))

slopes = []
for gain in (-12.0, 3.0, 12.0):
    for S in (0.3, 1.0, 1.5):
        A = 10 ** (gain / 40)
        r = (A + 1 / A) * (1 / S - 1) + 2
        if r > 0:
            slopes.append("{:gain %s :S %s :Q %s}" % (f(gain), f(S), f(1 / np.sqrt(r))))

OUT.parent.mkdir(parents=True, exist_ok=True)
with open(OUT, "w") as fo:
    fo.write(";; generated by utils/fastmath/dev/generate_biquad_reference.py\n")
    fo.write("{:filters [" + "\n ".join(entries) + "]\n :slopes [" + " ".join(slopes) + "]}\n")

print("filters:", len(entries), "slopes:", len(slopes))
print("wrote", OUT)
