"""Generator of reference values for `fastmath.signal.test-signals-test`.

Produces `test/resources/signal/test_signals_reference.edn`: WaveLab `MakeSignal`
formulas (Donoho-Johnstone) for Blocks, Bumps, HeaviSine and Doppler at
t = (1..1024)/1024.

Run from anywhere:
    cd /home/ts/penv && uv run python \
        /home/ts/clojure/fastmath/utils/fastmath/dev/generate_test_signals_reference.py
"""
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "test" / "resources" / "signal" / "test_signals_reference.edn"

n = 1024
t = np.arange(1, n + 1) / n
pos = np.array([.1, .13, .15, .23, .25, .40, .44, .65, .76, .78, .81])

hgt = np.array([4, -5, 3, -4, 5, -4.2, 2.1, 4.3, -3.1, 2.1, -4.2])
blocks = np.sum([(1 + np.sign(t - p)) * (h / 2) for p, h in zip(pos, hgt)], 0)

hgt = np.array([4, 5, 3, 4, 5, 4.2, 2.1, 4.3, 3.1, 5.1, 4.2])
wth = np.array([.005, .005, .006, .01, .01, .03, .01, .01, .005, .008, .005])
bumps = np.sum([h / (1 + np.abs((t - p) / w)) ** 4 for p, h, w in zip(pos, hgt, wth)], 0)

heavisine = 4 * np.sin(4 * np.pi * t) - np.sign(t - .3) - np.sign(.72 - t)
doppler = np.sqrt(t * (1 - t)) * np.sin(2 * np.pi * 1.05 / (t + .05))


def vec(xs):
    return "[" + " ".join(repr(float(x)) for x in xs) + "]"


OUT.parent.mkdir(parents=True, exist_ok=True)
with open(OUT, "w") as fo:
    fo.write(";; generated by utils/fastmath/dev/generate_test_signals_reference.py\n")
    fo.write("{:t %s\n :blocks %s\n :bumps %s\n :heavisine %s\n :doppler %s}\n"
             % (vec(t), vec(blocks), vec(bumps), vec(heavisine), vec(doppler)))

print("wrote", OUT)
