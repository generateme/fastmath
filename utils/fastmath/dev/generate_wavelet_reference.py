"""Generator of reference values for `fastmath.transform.wavelets-test`.

Produces `test/resources/transform/wavelet_reference.edn` with PyWavelets results:

- `:dwt` - one level `pywt.dwt` -> [cA cD],
- `:wavedec` - `pywt.wavedec` at the default (maximum) level, `:wavedec2` at level 2,
for 12 wavelets x 9 modes x N in (1, 2, 5, 16, 31, 64), skipping combinations
PyWavelets rejects (one-sample signal with reflect / antireflect);

- `:packets` - `pywt.WaveletPacket` nodes of levels 1-3 (natural order) for
4 wavelets x 3 modes x N in (16, 37);

- `:wavefun` - `pywt.Wavelet.wavefun(level=10)` interpolated on 101 points of its
grid for 12 wavelets (orthogonal: phi, psi; biorthogonal: decomposition and
reconstruction phi, psi).

Inputs are deterministic (seeded) and stored with the results.

Run from anywhere:
    cd /home/ts/penv && uv run python \
        /home/ts/clojure/fastmath/utils/fastmath/dev/generate_wavelet_reference.py
"""
import warnings
from pathlib import Path

import numpy as np
import pywt

warnings.simplefilter("ignore")   # pywt warns about levels with boundary effects

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "test" / "resources" / "transform" / "wavelet_reference.edn"

WAVELETS = ["haar", "db2", "db4", "db10", "sym5", "sym8", "coif3", "bior2.2", "bior3.5", "bior6.8", "rbio2.2", "dmey"]
MODES = ["zero", "constant", "symmetric", "reflect", "periodic", "smooth", "antisymmetric", "antireflect", "periodization"]
FM_MODE = {"constant": "constant", "smooth": "smooth"}
LENGTHS = [1, 2, 5, 16, 31, 64]
rng = np.random.default_rng(20261012)


def f(x):
    return repr(float(x))


def vec(xs):
    return "[" + " ".join(f(x) for x in xs) + "]"


def vecs(xss):
    return "[" + " ".join(vec(xs) for xs in xss) + "]"


signals = {n: np.round(rng.uniform(-5, 5, n), 6) for n in LENGTHS + [37]}

entries = []
for w in WAVELETS:
    for mode in MODES:
        for n in LENGTHS:
            x = signals[n]
            try:
                da = pywt.dwt(x, w, mode)
            except ValueError:
                continue
            dec = pywt.wavedec(x, w, mode)
            try:
                dec2 = vecs(pywt.wavedec(x, w, mode, level=2))
            except ValueError:   # the level-1 approximation has one sample (reflect / antireflect)
                dec2 = "nil"
            entries.append("{:wavelet \"%s\" :mode :%s :n %d :x %s :dwt %s :wavedec %s :wavedec2 %s}"
                           % (w, mode, n, vec(x), vecs(da), vecs(dec), dec2))

packets = []
for w in ["haar", "db4", "sym5", "bior3.5"]:
    for mode in ["symmetric", "periodization", "zero"]:
        for n in [16, 37]:
            x = signals[n]
            wp = pywt.WaveletPacket(x, w, mode, maxlevel=3)
            levels = [vecs([node.data for node in wp.get_level(k, order="natural")]) for k in (1, 2, 3)]
            packets.append("{:wavelet \"%s\" :mode :%s :n %d :x %s :levels [%s]}"
                           % (w, mode, n, vec(x), " ".join(levels)))

wavefuns = []
for w in ["haar", "db2", "db4", "sym4", "coif1", "dmey", "bior1.3", "bior2.2", "bior3.5", "bior4.4", "rbio2.2", "rbio3.1"]:
    W = pywt.Wavelet(w)
    res = W.wavefun(level=10)
    xs = res[-1]
    grid = np.linspace(xs[0], xs[-1], 101)
    names = [":phi", ":psi"] if len(res) == 3 else [":phi", ":psi", ":phi-rec", ":psi-rec"]
    parts = " ".join("%s %s" % (k, vec(np.interp(grid, xs, fn))) for k, fn in zip(names, res[:-1]))
    wavefuns.append("{:wavelet \"%s\" :x %s %s}" % (w, vec(grid), parts))

OUT.parent.mkdir(parents=True, exist_ok=True)
with open(OUT, "w") as fo:
    fo.write(";; generated by utils/fastmath/dev/generate_wavelet_reference.py (pywt %s)\n" % pywt.__version__)
    fo.write("{:transforms [" + "\n ".join(entries) + "]\n :packets [" + "\n ".join(packets)
             + "]\n :wavefun [" + "\n ".join(wavefuns) + "]}\n")

print("transform cases:", len(entries), "packet cases:", len(packets))
print("wrote", OUT)
