% Generator of reference values for `fastmath.kernel.window-test` from Octave `signal` (kernel audit).
%
% Tool: Octave (tested with 11.x) with the `signal` package 1.4.7.
% Output: test/resources/kernel/window_octave_reference.edn, `:cases` of
%   {:id :window :opts :N :normalize? :expected}
% where `:normalize?` true means the default normalisation of the fastmath window (division by f(0) for
% continuous model windows, by the maximum for discrete ones), which is what these Octave functions return.
% Why: Octave is a second independent library (besides scipy) for chebwin (dolph-chebyshev, the accuracy
% limit shared with scipy, Findings W2-05), nuttallwin, blackmanharris, kaiser, gausswin and flattopwin
% (the B&K / Gade and Herlufsen set, 1 1.93 1.29 0.388 0.0322, used by the flat-top additions).
%
% Run (output is byte-identical on every run):
%   octave --no-gui /home/ts/clojure/fastmath/utils/fastmath/dev/generate_window_octave.m
pkg load signal

here = fileparts(mfilename('fullpath'));
out = fullfile(here, '..', '..', '..', 'test', 'resources', 'kernel', 'window_octave_reference.edn');
fid = fopen(out, 'w');
fprintf(fid, ';; Generated by utils/fastmath/dev/generate_window_octave.m (Octave %s, signal package 1.4.7).\n', version());
fprintf(fid, '{:cases [\n');

% `periodic` true: the case is the periodic window of N samples, which fastmath builds as the symmetric window of
% N + 1 samples without the last one (the test does this, :periodic true).
function emit(fid, window, opts, N, w, periodic)
  if nargin < 6
    periodic = false;
  end
  id = [window ' ' opts ' N=' num2str(N)];
  extra = '';
  if periodic
    id = [id ' periodic'];
    extra = ' :periodic true';
  end
  fprintf(fid, ' {:id "%s" :window :%s :opts %s :N %d :normalize? true', id, window, opts, N);
  fputs(fid, extra);
  fputs(fid, ' :expected [');
  fprintf(fid, '%.17g ', w(1:end-1));
  fprintf(fid, '%.17g]}\n', w(end));
end

% chebwin(N, at) = dolph-chebyshev {:level -at}
for at = [40 60 80 100]
  for N = [8 9 64 65]
    emit(fid, 'dolph-chebyshev', sprintf('{:level %.1f}', -at), N, chebwin(N, at));
  end
end

for N = [2 3 8 9 64]
  emit(fid, 'nutall-1st', '{}', N, nuttallwin(N));
  emit(fid, 'blackman-harris-92db', '{}', N, blackmanharris(N));
end

% flattopwin(N) = flat-top-bk (1 1.93 1.29 0.388 0.0322 / 4.6402), N = 1 .. 40 and powers of two +- 1 up to 256,
% symmetric and periodic (the periodic window is the symmetric window of N + 1 samples without the last one)
for N = [1:40 63 64 65 100 127 128 129 255 256]
  emit(fid, 'flat-top-bk', '{}', N, flattopwin(N, 'symmetric'));
  if N >= 2   % the periodic window of 1 sample is (1.0) by definition, not a part of the symmetric window of 2
    emit(fid, 'flat-top-bk', '{}', N, flattopwin(N, 'periodic'), true);
  end
end

% kaiser(N, beta) = kaiser-bessel {:alpha beta/pi} = kaiser {:beta beta}
for alpha = [0.5 1 2 3]
  for N = [8 9 64]
    emit(fid, 'kaiser-bessel', sprintf('{:alpha %.1f}', alpha), N, kaiser(N, pi * alpha));
  end
end
for beta = [0.5 3.5 8.6 14]
  for N = [1 2 8 9 64 65]
    emit(fid, 'kaiser', sprintf('{:beta %.1f}', beta), N, kaiser(N, beta));
  end
end

% gausswin(N, a) = gaussian {:alpha a}
for alpha = [1 2.5 3]
  for N = [8 9 64]
    emit(fid, 'gaussian', sprintf('{:alpha %.1f}', alpha), N, gausswin(N, alpha));
  end
end

fprintf(fid, ']}\n');
fclose(fid);
