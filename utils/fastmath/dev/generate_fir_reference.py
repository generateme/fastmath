"""Generator of reference values for `fastmath.signal.fir-test` (extended cases).

Produces `test/resources/signal/fir_reference.edn` with scipy.signal results:

- `:firwin` - `firwin` for hamming, blackman, boxcar windows, odd/even taps,
  automatic taps (fastmath rule floor(p fs / max_cutoff), p = 4, passed explicitly),
  fs 10 and 1000, numeric `scale` (normalized frequency),
- `:firwin2` - `firwin2` with nfreqs = 1 + 2^ceil(log2(1.25 taps)) (the fastmath
  default) for the four filter types, windows hann / boxcar, fs 1 and 10,
- `:gammatone` - `gammatone(1000, 'fir', fs=16000)` (defaults) and other orders.

Run from anywhere:
    cd /home/ts/penv && uv run python \
        /home/ts/clojure/fastmath/utils/fastmath/dev/generate_fir_reference.py
"""
import math
from pathlib import Path

import numpy as np
import scipy.signal as ss

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "test" / "resources" / "signal" / "fir_reference.edn"

WINDOWS = {"hamming": "hamming", "blackman": "blackman", "rectangular": "boxcar", "hann": "hann"}


def f(x):
    return repr(float(x))


def vec(xs):
    return "[" + " ".join(f(x) for x in xs) + "]"


def cutoff_edn(c):
    return f(c) if np.isscalar(c) else vec(c)


firwin = []
for fs in (1.0, 10.0, 1000.0):
    for kind, cutoff, pass_zero in [("lowpass", 0.12, True), ("highpass", 0.2, False),
                                    ("bandpass", [0.1, 0.3], False), ("bandstop", [0.1, 0.3], True)]:
        cutoff = np.array(cutoff) * fs if not np.isscalar(cutoff) else cutoff * fs
        for window in ("hamming", "blackman", "rectangular"):
            for taps in (21, 30, None):
                n = taps if taps else int(math.floor(4 * fs / np.max(cutoff)))
                if n % 2 == 0 and kind in ("highpass", "bandstop"):
                    n += 1
                h = ss.firwin(n, cutoff, window=WINDOWS[window], pass_zero=pass_zero, fs=fs)
                firwin.append("{:kind :%s :cutoff %s :fs %s :window :%s :taps %s :result %s}"
                              % (kind, cutoff_edn(cutoff), f(fs), window, str(taps) if taps else "nil", vec(h)))
        h = ss.firwin(31, cutoff, window="hann", pass_zero=pass_zero, fs=fs, scale=False)
        firwin.append("{:kind :%s :cutoff %s :fs %s :window :hann :taps 31 :scale? false :result %s}"
                      % (kind, cutoff_edn(cutoff), f(fs), vec(h)))

firwin2 = []
for fs in (1.0, 10.0):
    nyq = fs / 2
    for taps, antisym, freqs, gains in [(17, False, [0, 0.2, 0.3, 1.0], [1, 1, 0, 0]),
                                        (16, False, [0, 0.2, 0.3, 1.0], [1, 1, 0.5, 0]),
                                        (17, True, [0, 0.2, 0.6, 1.0], [0, 1, 1, 0]),
                                        (16, True, [0, 0.2, 0.6, 1.0], [0, 0.5, 1, 1])]:
        fr = [x * nyq for x in freqs]
        nfreqs = 1 + 2 ** math.ceil(math.log2(1.25 * taps))
        for window in ("hann", "rectangular"):
            h = ss.firwin2(taps, fr, gains, nfreqs=nfreqs, window=None if window == "rectangular" else "hann",
                           antisymmetric=antisym, fs=fs)
            firwin2.append("{:taps %d :antisymmetric? %s :pairs [%s] :fs %s :window %s :result %s}"
                           % (taps, "true" if antisym else "false",
                              " ".join("[%s %s]" % (f(a), f(b)) for a, b in zip(fr, gains)),
                              f(fs), "nil" if window == "rectangular" else ":hann", vec(h)))

gamma = []
for cutoff, fs, order, taps in [(1000.0, 16000.0, 4, None), (200.0, 1000.0, 4, 30), (440.0, 8000.0, 2, 64)]:
    b, _ = ss.gammatone(cutoff, "fir", order=order, numtaps=taps, fs=fs)
    gamma.append("{:cutoff %s :fs %s :order %d :taps %s :result %s}"
                 % (f(cutoff), f(fs), order, str(taps) if taps else "nil", vec(b)))

OUT.parent.mkdir(parents=True, exist_ok=True)
with open(OUT, "w") as fo:
    fo.write(";; generated by utils/fastmath/dev/generate_fir_reference.py\n")
    fo.write("{:firwin [" + "\n ".join(firwin) + "]\n :firwin2 [" + "\n ".join(firwin2)
             + "]\n :gammatone [" + "\n ".join(gamma) + "]}\n")

print("firwin:", len(firwin), "firwin2:", len(firwin2), "gammatone:", len(gamma))
print("wrote", OUT)
