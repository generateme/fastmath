"""Generator of reference values for `fastmath.signal.denoise-test`.

Produces `test/resources/signal/denoise_reference.edn`:

- `:sure` - MATLAB `thselect(x, 'rigrsure')` (ported below) for 20 seeded inputs
  of lengths 1..60,
- `:thresholds` - thresholds of one coefficient vector (formulas below, numpy),
- `:pipelines` - PyWavelets denoising: `wavedec` -> one threshold for all detail
  bands -> `pywt.threshold` -> `waverec`, cut to the signal length.

Threshold formulas (`sigma_r` = median(|x - median(x)|) / 0.6744897501960816,
`n` = number of coefficients the threshold is estimated from):
  visu = sigma_r * sqrt(2 ln n); universal = std(x, ddof=1) * sqrt(2 ln n);
  sure = sigma_r * rigrsure(x / sigma_r); hybrid = sigma_r * heursure(x / sigma_r);
  avg = mean |x|; peaksavg = (min |x| + max |x|) / 2;
  topn = quantile(|x|, 0.75, method='weibull').
Pipelines estimate from the finest detail band (visu, universal) or from all
detail bands (sure, hybrid).

Run from anywhere:
    cd /home/ts/penv && uv run python \
        /home/ts/clojure/fastmath/utils/fastmath/dev/generate_denoise_reference.py
"""
from pathlib import Path

import numpy as np
import pywt

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "test" / "resources" / "signal" / "denoise_reference.edn"
rng = np.random.default_rng(20261012)


def rigrsure(x):
    n = len(x)
    sx2 = np.sort(np.abs(x)) ** 2
    risks = (n - 2 * np.arange(1, n + 1) + np.cumsum(sx2) + np.arange(n - 1, -1, -1) * sx2) / n
    return np.sqrt(sx2[np.argmin(risks)])


def heursure(x):
    n = len(x)
    hthr = np.sqrt(2 * np.log(n))
    eta = (np.dot(x, x) - n) / n
    crit = np.log2(n) ** 1.5 / np.sqrt(n)
    return hthr if eta < crit else min(rigrsure(x), hthr)


def sigma_r(x):
    return np.median(np.abs(x - np.median(x))) / 0.6744897501960816


def thresholds(x):
    n = len(x)
    s = sigma_r(x)
    return {"visu": s * np.sqrt(2 * np.log(n)),
            "universal": np.std(x, ddof=1) * np.sqrt(2 * np.log(n)),
            "sure": s * rigrsure(x / s),
            "hybrid": s * heursure(x / s),
            "avg": np.mean(np.abs(x)),
            "peaksavg": (np.min(np.abs(x)) + np.max(np.abs(x))) / 2,
            "topn": np.quantile(np.abs(x), 0.75, method="weibull")}


def f(x):
    return repr(float(x))


def vec(xs):
    return "[" + " ".join(f(x) for x in xs) + "]"


sure_cases = []
for n in [1, 2, 3, 5, 8, 13, 21, 34, 55, 60] * 2:
    x = np.round(rng.normal(0, 1.5, n), 6)
    sure_cases.append("{:x %s :sure %s}" % (vec(x), f(rigrsure(x))))

coeffs = np.round(rng.normal(0, 1, 64) + np.where(rng.uniform(size=64) < 0.1, rng.normal(0, 8, 64), 0), 6)
thr = thresholds(coeffs)
thr_edn = "{:x %s %s}" % (vec(coeffs), " ".join(":%s %s" % (k, f(v)) for k, v in thr.items()))

t = np.linspace(0, 1, 301)
clean = np.where(t < 0.3, 1.0, np.where(t < 0.6, -2.0, 0.5)) + np.sin(12 * t)
signal = np.round(clean + rng.normal(0, 0.3, len(t)), 6)

pipelines = []
for w in ["db4", "sym8", "haar"]:
    for mode in ["symmetric", "periodization"]:
        c = pywt.wavedec(signal, w, mode)
        for rule in ["visu", "universal", "sure", "hybrid"]:
            estimate = c[-1] if rule in ("visu", "universal") else np.concatenate(c[1:])
            lam = thresholds(estimate)[rule]
            for method in ["hard", "soft", "garrote"]:
                d = [c[0]] + [pywt.threshold(b, lam, method) for b in c[1:]]
                rec = pywt.waverec(d, w, mode)[:len(signal)]
                pipelines.append("{:wavelet \"%s\" :mode :%s :thr :%s :method :%s :lambda %s :result %s}"
                                 % (w, mode, rule, method, f(lam), vec(rec)))

OUT.parent.mkdir(parents=True, exist_ok=True)
with open(OUT, "w") as fo:
    fo.write(";; generated by utils/fastmath/dev/generate_denoise_reference.py (pywt %s)\n" % pywt.__version__)
    fo.write("{:sure [" + "\n ".join(sure_cases) + "]\n :thresholds " + thr_edn
             + "\n :signal " + vec(signal) + "\n :pipelines [" + "\n ".join(pipelines) + "]}\n")

print("sure:", len(sure_cases), "pipelines:", len(pipelines))
print("wrote", OUT)
