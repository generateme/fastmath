"""Generator of reference values for `fastmath.signal.chirp-test`.

Produces `test/resources/signal/chirp_reference.edn` with `scipy.signal.chirp`
values (phi = -90 + 360 * phase0 degrees, i.e. a sine) on 301 points of
[0, 3] shifted by 0.0013, for every method, f0 = 1, f1 = 6, t1 = 2 (the hyperbolic singularity
t = 2.4 is inside the range), f0 = f1 = 3 for logarithmic and hyperbolic, and a
decreasing sweep f0 = 6, f1 = 1.

Run from anywhere:
    cd /home/ts/penv && uv run python \
        /home/ts/clojure/fastmath/utils/fastmath/dev/generate_chirp_reference.py
"""
from pathlib import Path

import numpy as np
import scipy.signal as ss

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "test" / "resources" / "signal" / "chirp_reference.edn"

t = np.linspace(0, 3, 301) + 0.0013   # shifted so the singular point t = 2.4 is not sampled


def f(x):
    return repr(float(x))


def vec(xs):
    return "[" + " ".join(f(x) for x in xs) + "]"


entries = []
for f0, f1 in [(1.0, 6.0), (6.0, 1.0), (3.0, 3.0)]:
    for kind, method, vz in [("linear", "linear", True), ("quadratic-up", "quadratic", True),
                             ("quadratic-down", "quadratic", False), ("logarithmic", "logarithmic", True),
                             ("hyperbolic", "hyperbolic", True)]:
        for phase0 in (0.0, 0.25):
            y = ss.chirp(t, f0, 2.0, f1, method=method, phi=-90 + 360 * phase0, vertex_zero=vz)
            entries.append("{:type :%s :f0 %s :f1 %s :time 2.0 :phase0 %s :y %s}"
                           % (kind, f(f0), f(f1), f(phase0), vec(y)))

OUT.parent.mkdir(parents=True, exist_ok=True)
with open(OUT, "w") as fo:
    fo.write(";; generated by utils/fastmath/dev/generate_chirp_reference.py\n")
    fo.write("{:t " + vec(t) + "\n :chirps [" + "\n ".join(entries) + "]}\n")

print("chirps:", len(entries))
print("wrote", OUT)
