"""Generator of reference values for `fastmath.signal.pad-test`.

Produces `test/resources/signal/pad_reference.edn` with `pywt.pad` results for
every fastmath padding method, every side and several target lengths,
including paddings longer than the signal (repeated extension) and
one-sample signals.

fastmath method -> PyWavelets mode:
  zero -> zero, edge -> constant, periodic -> periodic, symmetric -> symmetric,
  reflect -> reflect, antisymmetric -> antisymmetric, antireflect -> antireflect,
  linear -> smooth

Side -> (before, after) for an extra length `e = N - len`:
  left (e, 0), right (0, e), both (ceil(e/2), floor(e/2))

Run from anywhere:
    cd /home/ts/penv && uv run python \
        /home/ts/clojure/fastmath/utils/fastmath/dev/generate_pad_reference.py
"""
from pathlib import Path

import numpy as np
import pywt

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "test" / "resources" / "signal" / "pad_reference.edn"

MODES = {"zero": "zero", "edge": "constant", "periodic": "periodic",
         "symmetric": "symmetric", "reflect": "reflect",
         "antisymmetric": "antisymmetric", "antireflect": "antireflect",
         "linear": "smooth"}

SIGNALS = [[3.5],
           [1.0, 4.0],
           [-1.0, 2.0, 0.5],
           [-1.0, 2.0, 0.0, 5.0, 10.0],
           [0.25, -3.0, 7.5, 2.0, -0.5, 1.0]]


def widths(side, extra):
    if side == "left":
        return (extra, 0)
    if side == "right":
        return (0, extra)
    return ((extra + 1) // 2, extra // 2)


def fmt(x):
    return repr(float(x))


entries = []
for s in SIGNALS:
    n = len(s)
    for N in sorted({n, n + 1, 2 * n + 3, 3 * n, 3 * n + 7}):
        for side in ("left", "right", "both"):
            for fm, pm in MODES.items():
                res = pywt.pad(np.array(s), widths(side, N - n), pm)
                assert len(res) == N
                entries.append("{:method :%s :side :%s :N %d :signal [%s] :result [%s]}"
                               % (fm, side, N, " ".join(fmt(x) for x in s),
                                  " ".join(fmt(x) for x in res)))

OUT.parent.mkdir(parents=True, exist_ok=True)
with open(OUT, "w") as f:
    f.write(";; generated by utils/fastmath/dev/generate_pad_reference.py (pywt %s)\n" % pywt.__version__)
    f.write("[" + "\n ".join(entries) + "]\n")

print("entries:", len(entries))
print("wrote", OUT)
