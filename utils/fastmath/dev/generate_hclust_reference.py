"""SciPy reference data for the hierarchical clustering tests in test/fastmath/ml/clustering_test.clj

Tools: Python 3.14, numpy, SciPy 1.18.1 (scipy.cluster.hierarchy.linkage, cophenet).
Run: cd /home/ts/penv && uv run python /home/ts/clojure/fastmath/utils/fastmath/dev/generate_hclust_reference.py
Output: test/resources/clustering/hclust_scipy_reference.edn (regeneration is byte-identical:
fixed data, repr() of doubles).

Why: SciPy is the second oracle of fastmath.ml.clustering/hclust and the definition of
:centroid and :median (squared distances, square roots of heights). It checks the linkage
matrix (->linkage-matrix) and the cophenetic correlation. Only tie-free sets (and the
3-point triangle for inversions): with ties SciPy can return another tree than R.
Method names: SciPy 'weighted' is :weighted, 'ward' is :ward; SciPy has no :ward-d.
The datasets are the formulas of generate_hclust_reference.R.
"""
import os
import math
import numpy as np
from scipy.cluster.hierarchy import linkage, cophenet
from scipy.spatial.distance import pdist

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..",
                   "test", "resources", "clustering", "hclust_scipy_reference.edn")

x8 = np.array([[-0.626, 0.576], [0.184, -0.305], [-0.836, 1.512], [1.595, 0.39],
               [0.33, -0.621], [-0.82, -2.215], [0.487, 1.125], [0.738, -0.045]])
x30 = np.array([[round(math.sin(i * 1.3 + j * 2.1) * 3 + math.cos(i * j * 0.7), 3)
                 for j in range(1, 4)] for i in range(1, 31)])
triangle = np.array([[0, 0], [1, 0], [0.51, 0.85]])

METHODS = ["single", "complete", "average", "weighted", "centroid", "median", "ward"]


def num(x):
    return "##NaN" if math.isnan(x) else repr(float(x))


def row(r):
    return "[%d %d %s %d]" % (int(r[0]), int(r[1]), num(r[2]), int(r[3]))


def dataset(d):
    entries = []
    for m in METHODS:
        z = linkage(d, m)
        c, _ = cophenet(z, d) if len(d) > 1 else (float("nan"), None)
        entries.append(":%s {:linkage [%s]\n  :cophenetic-correlation %s}" %
                       (m, " ".join(row(r) for r in z), num(c)))
    return "{" + "\n ".join(entries) + "}"


sets = {"x8": pdist(x8), "x30": pdist(x30), "manhattan": pdist(x8, "cityblock"),
        "triangle": pdist(triangle)}

with open(OUT, "w") as f:
    f.write(";; generated by utils/fastmath/dev/generate_hclust_reference.py, do not edit\n")
    f.write("{" + "\n".join(":%s %s" % (k, dataset(v)) for k, v in sets.items()) + "}\n")
