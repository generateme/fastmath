"""Generator of reference values for `fastmath.signal.waveform-test`.

Produces `test/resources/signal/waveform_reference.edn`: for t on 401 points of
[-2, 2] shifted by 0.00123 (no sample at a jump), f = 2, phase = 0.1,
amplitude = 1.5, phase(t) = 0.1 + 2 t:

- `:sine` = 1.5 sin(2 pi phase),
- `:square` = 1.5 scipy.signal.square(2 pi phase, duty=0.3),
- `:saw-up` = 1.5 scipy.signal.sawtooth(2 pi (phase + 1/2)), `:saw-down` with width=0,
- `:triangle` = 1.5 scipy.signal.sawtooth(2 pi (phase + 1/4), 0.5),
- band-limited Fourier sums with 7 bands (numpy).

Run from anywhere:
    cd /home/ts/penv && uv run python \
        /home/ts/clojure/fastmath/utils/fastmath/dev/generate_waveform_reference.py
"""
from pathlib import Path

import numpy as np
import scipy.signal as ss

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "test" / "resources" / "signal" / "waveform_reference.edn"

t = np.linspace(-2, 2, 401) + 0.00123
ph = 0.1 + 2 * t
A = 1.5
k = np.arange(7)[:, None]

res = {
    "sine": A * np.sin(2 * np.pi * ph),
    "square": A * ss.square(2 * np.pi * ph, duty=0.3),
    "saw-up": A * ss.sawtooth(2 * np.pi * (ph + 0.5)),
    "saw-down": A * ss.sawtooth(2 * np.pi * (ph + 0.5), width=0),
    "triangle": A * ss.sawtooth(2 * np.pi * (ph + 0.25), 0.5),
    "band-limited-square": A * 4 / np.pi * np.sum(np.sin(2 * np.pi * (2 * k + 1) * ph) / (2 * k + 1), 0),
    "band-limited-saw": A * 2 / np.pi * np.sum((-1.0) ** k * np.sin(2 * np.pi * (k + 1) * ph) / (k + 1), 0),
    "band-limited-triangle": A * 8 / np.pi ** 2 * np.sum((-1.0) ** k * np.sin(2 * np.pi * (2 * k + 1) * ph) / (2 * k + 1) ** 2, 0),
}


def vec(xs):
    return "[" + " ".join(repr(float(x)) for x in xs) + "]"


OUT.parent.mkdir(parents=True, exist_ok=True)
with open(OUT, "w") as fo:
    fo.write(";; generated by utils/fastmath/dev/generate_waveform_reference.py\n")
    fo.write("{:t " + vec(t) + "\n" + "\n".join(" :%s %s" % (k_, vec(v)) for k_, v in res.items()) + "}\n")

print("wrote", OUT)
