"""Generator of reference data for the distribution API layer of `fastmath.random`
(Random Audit WP 5.3, 5.4, 5.5; test file test/fastmath/random/distribution_api_test.clj).

Everything which the other reference files already hold is NOT repeated here: Commons overrides (5.1,
`dist_override_reference.edn`), `inverse-gaussian` cdf (5.2, `native_distributions_reference.edn`), `ccdf` of the
closed-form and SSJ families (5.4, `truncated_mixture_reference.edn`), multi-normal with explicit means
(5.5, `native_distributions_reference.edn`).  This file adds what they lack:

    :multi-normal-zero-mean   constructor call with `:covariances` only (the default `:means` is the zero vector of
                              the covariance dimension): dimensions 1..4 (seeded SPD covariance), 4 interior
                              points each, pdf and log-pdf; scipy `multivariate_normal(mean=zeros)`.
    :normal-sf                `ccdf` of the standard normal at the tail points 5, 8, 8.3, 10, 20, 37 and at -8.3
                              (sf = 1.0): scipy `norm.sf` (the old `1 - cdf` gave 0.0 from 8.29 on).
    :cdf-range                `cdf` with three arguments, P(v1 < X <= v2), scipy `cdf(v2) - cdf(v1)` for normal,
                              gamma, exponential, laplace, poisson (both arguments floored), binomial; the
                              pairs have v1 <= v2.

Tool: scipy.stats (version in the header of the produced file), numpy `default_rng(seed)` for the generated
covariances and points only (fixed seeds, deterministic).
Precision: double precision closed forms of scipy (relative error ~1e-15); the arguments are exact doubles printed
with `repr`, the reference is a function of those exact doubles.
Domain: see above.

Run:  cd /home/ts/penv && uv run python /home/ts/clojure/fastmath/utils/fastmath/dev/generate_random_dist_api_reference.py
Output: test/resources/random/dist_api_reference.edn (deterministic, byte-identical on rerun).
"""
import math
import os

import numpy as np
import scipy
from scipy import stats as st

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..",
                   "test", "resources", "random", "dist_api_reference.edn")


def num(x):
    x = float(x)
    if math.isnan(x):
        return "##NaN"
    if math.isinf(x):
        return "##Inf" if x > 0 else "##-Inf"
    return repr(x)


def vec(xs):
    return "[" + " ".join(num(x) for x in xs) + "]"


def mat(rows):
    return "[" + " ".join(vec(r) for r in rows) + "]"


def multi_normal_zero_mean():
    rng = np.random.default_rng(20261021)
    out = []
    for dim in range(1, 5):
        a = rng.standard_normal((dim, dim))
        s = a @ a.T + 0.5 * np.eye(dim)
        s = (s + s.T) / 2.0
        pts = [rng.standard_normal(dim) * 1.5 for _ in range(4)]
        d = st.multivariate_normal(np.zeros(dim), s)
        out.append("{:covariances %s\n   :points %s\n   :pdf %s\n   :lpdf %s}"
                   % (mat(s), mat(pts), vec([d.pdf(x) for x in pts]), vec([d.logpdf(x) for x in pts])))
    return "[" + "\n  ".join(out) + "]"


def normal_sf():
    xs = [5.0, 8.0, 8.3, 10.0, 20.0, 37.0, -8.3, 0.0, 1.5]
    return "{:xs %s\n   :sf %s}" % (vec(xs), vec([st.norm.sf(x) for x in xs]))


def cdf_range():
    cases = [
        ("normal", {":mu": 0.0, ":sd": 1.0}, st.norm(0.0, 1.0), [(-1.0, 1.0), (0.5, 3.0), (-4.0, -2.0), (1.0, 1.0), (-0.25, 0.0)]),
        ("gamma", {":shape": 2.5, ":scale": 1.5}, st.gamma(2.5, scale=1.5), [(0.5, 2.0), (1.0, 20.0), (3.0, 3.5)]),
        ("exponential", {":mean": 2.0}, st.expon(scale=2.0), [(0.1, 0.2), (0.0, 5.0), (3.0, 9.0)]),
        ("laplace", {":mu": 1.0, ":beta": 2.0}, st.laplace(1.0, 2.0), [(-3.0, 1.0), (0.0, 4.0), (2.0, 2.5)]),
        ("poisson", {":p": 4.0}, st.poisson(4.0), [(1.0, 4.0), (1.5, 4.9), (0.0, 10.0), (3.0, 3.0)]),
        ("binomial", {":trials": 10, ":p": 0.3}, st.binom(10, 0.3), [(1.0, 4.0), (2.5, 6.5), (0.0, 10.0)]),
    ]
    out = []
    for key, params, d, pairs in cases:
        p = "{" + " ".join("%s %s" % (k, num(v) if isinstance(v, float) else v) for k, v in params.items()) + "}"
        rows = []
        for v1, v2 in pairs:
            if key in ("poisson", "binomial"):
                e = d.cdf(math.floor(v2)) - d.cdf(math.floor(v1))
            else:
                e = d.cdf(v2) - d.cdf(v1)
            rows.append("[%s %s %s]" % (num(v1), num(v2), num(e)))
        out.append("{:key :%s\n   :params %s\n   :ranges [%s]}" % (key, p, " ".join(rows)))
    return "[" + "\n  ".join(out) + "]"


def main():
    header = (";; Reference data for the distribution API layer of fastmath.random (Random Audit, WP 5.3-5.5).\n"
              ";; Generated by utils/fastmath/dev/generate_random_dist_api_reference.py with scipy %s, numpy %s.\n"
              ";; Double precision scipy closed forms; do not edit by hand. ##Inf / ##-Inf / ##NaN are EDN literals.\n"
              % (scipy.__version__, np.__version__))
    body = "{:multi-normal-zero-mean %s\n\n :normal-sf %s\n\n :cdf-range %s}\n" % (
        multi_normal_zero_mean(), normal_sf(), cdf_range())
    with open(OUT, "w") as f:
        f.write(header + body)
    print("written", OUT)


if __name__ == "__main__":
    main()
