"""Generator of reference data for the five Commons Math overrides of `fastmath.java.dist`
(Random Audit, work package 5.1).

Oracle: scipy.stats (version recorded in the header of the produced file).

Overridden behaviours (Commons Math 3.6.1 value in brackets):
    logistic   variance  pi^2 s^2 / 3                      (pi^2 / (3 s^2))
    gumbel     mean      mu + beta * 0.5772156649015329     (gamma = 0.5778636748954609)
    nakagami   cdf       0 for x <= 0                       (cdf of |x|)
    f          pdf, logpdf for x < 0 (0, -Inf) and x = 0   (NaN)
    levy       pdf, logpdf, cdf for x <= mu (0, -Inf, 0)   (NaN)

Parameter sets: the library defaults and non-default sets, the last of each family is extreme.
The F distribution has one set per regime of the density at 0: d1 < 2 (+Inf), d1 = 2 (1), d1 > 2 (0).

Parameter mapping to scipy:
    logistic(mu, s)         -> logistic(loc = mu, scale = s)
    gumbel(mu, beta)        -> gumbel_r(loc = mu, scale = beta)
    nakagami(mu, omega)     -> nakagami(nu = mu, scale = sqrt(omega))
    f(d1, d2)               -> f(dfn = d1, dfd = d2)
    levy(mu, c)             -> levy(loc = mu, scale = c)

Run:  cd /home/ts/penv && uv run python /home/ts/clojure/fastmath/utils/fastmath/dev/generate_random_override_reference.py
Output: test/resources/random/dist_override_reference.edn (deterministic, byte-identical on rerun).
"""
import math
import os

import numpy as np
import scipy
from scipy import stats

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..",
                   "test", "resources", "random", "dist_override_reference.edn")


def num(x):
    x = float(x)
    if math.isnan(x):
        return "##NaN"
    if math.isinf(x):
        return "##Inf" if x > 0 else "##-Inf"
    return repr(x)


def vec(xs):
    return "[" + " ".join(num(x) for x in xs) + "]"


def params(d):
    return "{" + " ".join(":%s %s" % (k, num(v)) for k, v in d.items()) + "}"


def entry(p, fields):
    return "{:params %s\n   %s}" % (params(p), "\n   ".join(":%s %s" % (k, v) for k, v in fields))


sections = []

# logistic: variance
logistic = []
for p in [dict(mu=0.0, s=1.0), dict(mu=2.5, s=0.3), dict(mu=-1.0e4, s=1.0e5), dict(mu=0.0, s=1.0e-5)]:
    d = stats.logistic(loc=p["mu"], scale=p["s"])
    logistic.append(entry(p, [("variance", num(d.var())), ("mean", num(d.mean()))]))
sections.append(":logistic [" + "\n  ".join(logistic) + "]")

# gumbel: mean
gumbel = []
for p in [dict(mu=1.0, beta=2.0), dict(mu=-3.0, beta=0.25), dict(mu=1.0e6, beta=1.0e-3), dict(mu=-2.0, beta=1.0e7)]:
    d = stats.gumbel_r(loc=p["mu"], scale=p["beta"])
    gumbel.append(entry(p, [("mean", num(d.mean())), ("variance", num(d.var()))]))
sections.append(":gumbel [" + "\n  ".join(gumbel) + "]")

# nakagami: cdf for x <= 0
nakagami = []
xs_nak = [-1.0e6, -1000.0, -3.0, -1.0, -0.5, -1e-3, -1e-300, 0.0]
for p in [dict(mu=1.0, omega=1.0), dict(mu=0.5, omega=2.0), dict(mu=2.5, omega=0.3), dict(mu=100.0, omega=1.0e4)]:
    d = stats.nakagami(p["mu"], scale=math.sqrt(p["omega"]))
    nakagami.append(entry(p, [("xs", vec(xs_nak)), ("cdf", vec([d.cdf(x) for x in xs_nak]))]))
sections.append(":nakagami [" + "\n  ".join(nakagami) + "]")

# f: pdf, logpdf for x <= 0
f_sets = [dict(d1=1.0, d2=1.0),      # default: d1 < 2
          dict(d1=2.0, d2=7.0),      # d1 = 2
          dict(d1=5.0, d2=7.0),      # d1 > 2
          dict(d1=0.5, d2=1.0e6),    # extreme, d1 < 2
          dict(d1=300.0, d2=0.5)]    # extreme, d1 > 2
xs_f = [-1.0e6, -1000.0, -3.0, -1.0, -1e-3, -1e-300, 0.0]
fs = []
for p in f_sets:
    d = stats.f(p["d1"], p["d2"])
    fs.append(entry(p, [("xs", vec(xs_f)), ("pdf", vec([d.pdf(x) for x in xs_f])),
                        ("logpdf", vec([d.logpdf(x) for x in xs_f])), ("cdf", vec([d.cdf(x) for x in xs_f]))]))
sections.append(":f [" + "\n  ".join(fs) + "]")

# levy: pdf, logpdf, cdf for x <= mu
levy = []
for p in [dict(mu=0.0, c=1.0), dict(mu=3.5, c=0.7), dict(mu=-1.0e6, c=1.0e4), dict(mu=1.0e-3, c=1.0e-6)]:
    mu, c = p["mu"], p["c"]
    xs = [mu - 1.0e6 * c, mu - 1000.0 * c, mu - c, mu - 1e-3 * c, mu - 1e-300 if mu == 0.0 else np.nextafter(mu, -np.inf), mu]
    d = stats.levy(loc=mu, scale=c)
    levy.append(entry(p, [("xs", vec(xs)), ("pdf", vec([d.pdf(x) for x in xs])),
                          ("logpdf", vec([d.logpdf(x) for x in xs])), ("cdf", vec([d.cdf(x) for x in xs]))]))
sections.append(":levy [" + "\n  ".join(levy) + "]")

header = (";; Reference values for the Commons Math overrides of fastmath.java.dist (Random Audit, WP 5.1).\n"
          ";; Generated by utils/fastmath/dev/generate_random_override_reference.py with scipy %s, numpy %s.\n"
          ";; Do not edit by hand. ##Inf / ##-Inf / ##NaN are EDN literals.\n" % (scipy.__version__, np.__version__))
with open(OUT, "w") as fh:
    fh.write(header + "{" + "\n\n ".join(sections) + "}\n")
print("written", os.path.normpath(OUT))
